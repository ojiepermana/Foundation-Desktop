/// The pattern of each `text eol=lf` line in `.gitattributes`.
fn lf_rules() -> Vec<&'static str> {
    GITATTRIBUTES
        .lines()
        .filter_map(|line| line.trim().strip_suffix(" text eol=lf"))
        .collect()
}

/// Whether a per type `text eol=lf` line covers `path`.
fn has_lf_rule(path: &str) -> bool {
    let top = path.split('/').next().unwrap_or_default();
    let extension = path.rsplit('.').next().unwrap_or_default();
    lf_rules().iter().any(|rule| {
        rule.starts_with(&format!("/{top}/")) && rule.ends_with(&format!("*.{extension}"))
    })
}

/// Covers AC-5 (O-1, O-3 to O-6 of spec `_root/0003`, rule E-4): every
/// planned output carries the marker in its first three lines, is UTF-8
/// without BOM with one final newline, uses a relative `/` path under
/// `shared/assets/` or an app folder, and has a per type `text eol=lf`
/// line. JSON outputs are canonical with whole numbers only, and the shared
/// schema's `$comment` is the exact marker.
#[test]
fn every_output_follows_the_output_rules() {
    fn whole_numbers_only(path: &str, value: &Value) {
        match value {
            Value::Number(number) => {
                assert!(
                    number.is_u64() || number.is_i64(),
                    "O-5: {path} has {number}"
                );
            }
            Value::Array(items) => items.iter().for_each(|item| whole_numbers_only(path, item)),
            Value::Object(map) => map.values().for_each(|item| whole_numbers_only(path, item)),
            _ => {}
        }
    }
    for output in committed_plan().outputs {
        let (path, text) = (output.path.as_str(), output.contents.as_str());
        let head = text.lines().take(3).collect::<Vec<_>>().join("\n");
        for marker in ["Generated by desktop-codegen", "Do not edit"] {
            assert!(head.contains(marker), "O-1: {path} lacks {marker:?}");
        }
        assert!(!text.starts_with('\u{feff}'), "O-3: {path} has a BOM");
        assert!(
            text.ends_with('\n') && !text.ends_with("\n\n") && !text.contains('\r'),
            "O-3: {path} line endings"
        );
        assert!(
            !path.starts_with('/') && !path.contains('\\') && !path.contains(".."),
            "O-6: {path} is a plain relative path"
        );
        assert!(
            path.starts_with("shared/assets/") || path.starts_with("apps/"),
            "O-6: {path} lives in the source folder or an app folder"
        );
        assert!(
            has_lf_rule(path),
            "O-6: no per type text eol=lf line for {path}: {:?}",
            lf_rules()
        );
        if path.ends_with(".json") {
            let value: Value = serde_json::from_str(text).expect("output is JSON");
            assert_eq!(
                to_canonical_json(&value),
                text,
                "O-4: {path} is not canonical"
            );
            whole_numbers_only(path, &value);
            if path.starts_with("shared/assets/") {
                assert_eq!(
                    value["$comment"].as_str(),
                    Some(MARKER),
                    "O-1: {path} $comment"
                );
            }
        }
    }
}

/// Covers AC-6 (O-6): the manifest and every source the manifest derives
/// have a per type `text eol=lf` line, so `.json` and `.svg` keep LF.
#[test]
fn manifest_and_sources_have_lf_attributes() {
    let brand = assets::parse(&read(MANIFEST_PATH)).expect("the committed manifest is valid");
    let mut paths = vec![MANIFEST_PATH.to_string()];
    paths.extend(brand.assets.iter().flat_map(|asset| asset.source_paths()));
    for path in paths {
        assert!(
            has_lf_rule(&path),
            "AC-6: no per type text eol=lf line for {path}: {:?}",
            lf_rules()
        );
    }
}

/// Runs the command line with `args` and returns code, stdout, and stderr.
fn run(args: &[&str]) -> (Option<i32>, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_desktop-codegen"))
        .args(args)
        .output()
        .expect("the binary runs");
    (
        out.status.code(),
        String::from_utf8(out.stdout).expect("stdout is UTF-8"),
        String::from_utf8(out.stderr).expect("stderr is UTF-8"),
    )
}

/// Covers AC-3 and AC-4: `assets check` on the repo exits with 0 and prints
/// exactly the success line of `check`; `assets` and `assets nope` exit
/// with 2 and the usage lines list `assets`.
#[test]
fn assets_command_exit_codes() {
    let (code, stdout, stderr) = run(&["assets", "check"]);
    let line = check(&repo_root(), &assets::SOURCE).expect("committed outputs are up to date");
    assert_eq!(code, Some(0), "AC-3: exit code, stderr: {stderr}");
    assert_eq!(stdout, format!("{line}\n"), "AC-3: one success line");
    assert_eq!(stderr, "", "AC-3: nothing on stderr");
    for args in [&["assets"][..], &["assets", "nope"]] {
        let (code, stdout, stderr) = run(args);
        assert_eq!(code, Some(2), "AC-4: {args:?}");
        assert_eq!(stdout, "", "AC-4: {args:?}");
        assert!(
            stderr
                .lines()
                .nth(1)
                .is_some_and(|line| line.starts_with("sources: ") && line.contains("assets")),
            "AC-4: the sources line lists assets: {stderr}"
        );
    }
}
