//! Rule tests for the `assets` source of spec `_root/0005`, beyond the
//! seven contract tests in `assets_contract.rs`.
//!
//! They lock the edges of each rule (accepted and rejected right at the
//! line), the "Jalur gagal `plan`" table (what is reported and what is
//! skipped), that every violation is reported at once, the summary counts,
//! the `generate` and `check` round trip, the output rules O-1 to O-6 of
//! spec `_root/0003` for every planned output, the `text eol=lf` lines for
//! the `.json` and `.svg` files, and the command line. The rules live in
//! `docs/specs/_root/0005-aset-merek-bersama/index.md`. As the spec says,
//! the tests lock the path and the rule ID at the start of each message,
//! not the English text after it. Inputs are copies under
//! `env!("CARGO_TARGET_TMPDIR")`; `shared/assets/` is never edited. No
//! test counts or lists the planned outputs.

