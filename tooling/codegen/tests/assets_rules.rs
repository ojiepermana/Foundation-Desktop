/// Covers AC-4 ("Jalur gagal `plan`"): each failure path reports what the
/// table says and skips the rest.
#[test]
fn plan_failure_paths_skip_what_the_spec_says() {
    let broken_icon = icon_with("</svg>", "<script/></svg>");

    let root = fixture("folder_is_file", false);
    fs::remove_dir_all(root.join(DIR)).expect("remove");
    write(&root, DIR, "x");
    assert_eq!(
        plan_ids(&root),
        expect(&[(DIR, "A-1")]),
        "AC-4: folder is a file"
    );
    clean(&root);

    let root = fixture("no_manifest", true);
    fs::remove_file(root.join(MANIFEST_PATH)).expect("remove");
    write(&root, "shared/assets/source/extra.txt", "x");
    write(&root, ICON_PATH, &broken_icon);
    assert_eq!(
        plan_ids(&root),
        expect(&[(MANIFEST_PATH, "A-1")]),
        "AC-4: no brand.json skips A-2, A-3, and S"
    );
    clean(&root);

    let root = fixture("no_source", true);
    fs::remove_dir_all(root.join(SOURCE_DIR)).expect("remove");
    write(
        &root,
        MANIFEST_PATH,
        edit(
            &read(MANIFEST_PATH),
            "\"schemaVersion\": 1",
            "\"schemaVersion\": 2",
        ),
    );
    assert_eq!(
        plan_ids(&root),
        expect(&[(SOURCE_DIR, "A-1"), (MANIFEST_PATH, "A-2")]),
        "AC-4: no source/ skips A-3 and S, A-2 still runs"
    );
    clean(&root);

    let root = fixture("manifest_not_utf8", true);
    write(&root, MANIFEST_PATH, [0xFF, 0xFE, b'{', b'}']);
    write(&root, "shared/assets/source/extra.txt", "x");
    let problems = (assets::SOURCE.plan)(&root).expect_err("plan must fail");
    assert_eq!(
        ids(&problems),
        expect(&[(MANIFEST_PATH, "A-2")]),
        "AC-4: not UTF-8"
    );
    assert!(
        problems[0].message.starts_with("A-2: cannot read: "),
        "AC-4: {}",
        problems[0]
    );
    clean(&root);

    let root = fixture("parse_fails", true);
    write(
        &root,
        MANIFEST_PATH,
        edit(
            &read(MANIFEST_PATH),
            "\"schemaVersion\": 1",
            "\"schemaVersion\": 2",
        ),
    );
    write(&root, "shared/assets/source/extra.txt", "x");
    write(&root, ICON_PATH, &broken_icon);
    assert_eq!(
        plan_ids(&root),
        expect(&[(MANIFEST_PATH, "A-2")]),
        "AC-4: a parse failure skips A-3 and S"
    );
    clean(&root);

    let root = fixture("wrong_kinds", true);
    fs::remove_file(root.join(README_PATH)).expect("remove");
    fs::create_dir(root.join(README_PATH)).expect("mkdir");
    fs::remove_file(root.join(SCHEMA_PATH)).expect("remove");
    fs::create_dir(root.join(SCHEMA_PATH)).expect("mkdir");
    assert_eq!(
        plan_ids(&root),
        expect(&[(README_PATH, "A-1"), (SCHEMA_PATH, "A-1")]),
        "AC-4: folders where files belong"
    );
    clean(&root);

    let root = fixture("source_is_file", true);
    fs::remove_dir_all(root.join(SOURCE_DIR)).expect("remove");
    write(&root, SOURCE_DIR, &broken_icon);
    assert_eq!(
        plan_ids(&root),
        expect(&[(SOURCE_DIR, "A-1")]),
        "AC-4: source/ as a file skips A-3 and S"
    );
    clean(&root);

    let root = fixture("half_light_dark", true);
    write(
        &root,
        MANIFEST_PATH,
        edit(
            &read(MANIFEST_PATH),
            "\"variants\": \"any\"",
            "\"variants\": \"light-dark\"",
        ),
    );
    fs::rename(
        root.join(ICON_PATH),
        root.join("shared/assets/source/app-icon-light.svg"),
    )
    .expect("rename");
    write(&root, "shared/assets/source/old.svg", read(ICON_PATH));
    assert_eq!(
        plan_ids(&root),
        expect(&[
            ("shared/assets/source/app-icon-dark.svg", "A-3"),
            ("shared/assets/source/old.svg", "A-3"),
        ]),
        "AC-4: a missing variant and an extra file, the present variant is valid"
    );
    clean(&root);
}

