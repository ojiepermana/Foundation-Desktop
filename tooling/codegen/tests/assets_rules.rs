const GITATTRIBUTES: &str = include_str!("../../../.gitattributes");

/// The O-1 marker text of the manifest schema.
const MARKER: &str = "Generated by desktop-codegen from tooling/codegen/src/assets. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- assets generate";

/// The committed `app-icon` source, from the repo root.
const ICON_PATH: &str = "shared/assets/source/app-icon.svg";

/// Reads a committed file as text.
fn read(path: &str) -> String {
    fs::read_to_string(repo_root().join(path)).expect("the committed file is readable")
}

/// Replaces the first `find` with `replace` in `text`, failing when absent.
fn edit(text: &str, find: &str, replace: &str) -> String {
    assert!(text.contains(find), "{find:?} is not in the text");
    text.replacen(find, replace, 1)
}

/// The committed icon with the first `find` replaced.
fn icon_with(find: &str, replace: &str) -> String {
    edit(&read(ICON_PATH), find, replace)
}

/// `(path, rule ID)` of each problem, for example
/// `("shared/assets/notes.txt", "A-1")`.
fn ids(problems: &[Problem]) -> Vec<(String, String)> {
    let mut found: Vec<(String, String)> = problems
        .iter()
        .map(|problem| {
            let id = problem.message.split(':').next().unwrap_or_default();
            (problem.path.clone(), id.to_string())
        })
        .collect();
    found.sort();
    found
}

/// Expected `(path, rule ID)` pairs, sorted like [`ids`].
fn expect(pairs: &[(&str, &str)]) -> Vec<(String, String)> {
    let mut pairs: Vec<(String, String)> = pairs
        .iter()
        .map(|(path, id)| ((*path).to_string(), (*id).to_string()))
        .collect();
    pairs.sort();
    pairs
}

/// The `(path, rule ID)` pairs of `check_svg` for `text` and `asset_id`.
fn svg_ids(text: &str, asset_id: &str) -> Vec<(String, String)> {
    ids(&assets::check_svg(ICON_PATH, asset_id, text.as_bytes()))
}

/// The pairs of `plan` under `root`, which must fail.
fn plan_ids(root: &Path) -> Vec<(String, String)> {
    ids(&(assets::SOURCE.plan)(root).expect_err("plan must fail"))
}

/// A fresh `assets_rules_<test>` root with a copy of the four committed
/// files, or of all but the schema when `with_schema` is false.
fn fixture(test: &str, with_schema: bool) -> PathBuf {
    let root = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("assets_rules_{test}"));
    if root.exists() {
        fs::remove_dir_all(&root).expect("the old fixture can be removed");
    }
    fs::create_dir_all(root.join(SOURCE_DIR)).expect("the fixture folder can be made");
    let mut files = vec![README_PATH, MANIFEST_PATH, ICON_PATH];
    if with_schema {
        files.push(SCHEMA_PATH);
    }
    for path in files {
        fs::copy(repo_root().join(path), root.join(path)).expect("the committed file is copied");
    }
    root
}

/// Writes `contents` to `path` under `root`.
fn write(root: &Path, path: &str, contents: impl AsRef<[u8]>) {
    fs::write(root.join(path), contents).expect("the fixture file can be written");
}

/// Removes the fixture.
fn clean(root: &Path) {
    fs::remove_dir_all(root).expect("the fixture can be removed");
}

/// The committed plan.
fn committed_plan() -> Plan {
    (assets::SOURCE.plan)(&repo_root()).expect("the committed assets are valid")
}

/// The committed icon padded with a comment to exactly `size` bytes.
fn icon_of_size(size: usize) -> String {
    let icon = read(ICON_PATH);
    let filler = size - icon.len() - "<!---->\n".len();
    format!("{icon}<!--{}-->\n", "a".repeat(filler))
}

/// Covers AC-4 (S-1): a source of exactly the limit is accepted, one byte
/// more is rejected with one S-1 problem and nothing else.
#[test]
fn source_size_limit_is_inclusive() {
    assert_eq!(
        svg_ids(&icon_of_size(MAX_SOURCE_BYTES), "app-icon"),
        expect(&[]),
        "AC-4: {MAX_SOURCE_BYTES} bytes are allowed"
    );
    assert_eq!(
        svg_ids(&icon_of_size(MAX_SOURCE_BYTES + 1), "app-icon"),
        expect(&[(ICON_PATH, "S-1")]),
        "AC-4: one byte more is rejected"
    );
}

/// Covers AC-4 (S-1, S-2): when S-1 fails, or a declaration or comment is
/// not closed, the later S rules are skipped for that file.
#[test]
fn early_s_rule_failures_skip_the_later_rules() {
    let script = icon_with("</svg>", "<script/></svg>");
    for (label, text, rule) in [
        ("carriage return", script.replacen('\n', "\r\n", 1), "S-1"),
        ("byte order mark", format!("\u{feff}{script}"), "S-1"),
        (
            "unclosed declaration",
            format!("<?xml version=\"1.0\"\n{script}"),
            "S-2",
        ),
        (
            "unclosed comment",
            script.replacen("<rect", "<!-- <rect", 1),
            "S-2",
        ),
    ] {
        assert_eq!(
            svg_ids(&text, "app-icon"),
            expect(&[(ICON_PATH, rule)]),
            "AC-4: {label} gives only {rule}"
        );
    }
}

/// Covers AC-4 (S-2): the declaration is removed only at byte 0; anywhere
/// else `<?` is reported by S-2 alone.
#[test]
fn declaration_counts_only_at_the_first_byte() {
    let declared = format!("<?xml version=\"1.0\"?>\n{}", read(ICON_PATH));
    assert_eq!(
        svg_ids(&declared, "app-icon"),
        expect(&[]),
        "AC-4: at byte 0"
    );
    let late = format!("\n{declared}");
    assert_eq!(
        svg_ids(&late, "app-icon"),
        expect(&[(ICON_PATH, "S-2")]),
        "AC-4: not at byte 0"
    );
}

/// Covers AC-4 (S-3): every allowed element is accepted, names are the
/// exact case sensitive letters, and a `<` in text must be `&lt;`.
#[test]
fn element_names_are_exact_and_case_sensitive() {
    let all: String = ALLOWED_ELEMENTS
        .iter()
        .map(|name| format!("<{name}/>"))
        .collect();
    let every = icon_with("</svg>", &format!("{all}<g\t/><g >x</g ></svg>"));
    assert_eq!(
        svg_ids(&every, "app-icon"),
        expect(&[]),
        "AC-4: allowed list"
    );
    let escaped = icon_with("</title>", " a &lt; b</title>");
    assert_eq!(
        svg_ids(&escaped, "app-icon"),
        expect(&[]),
        "AC-4: &lt; in text"
    );
    for (label, find, replace) in [
        ("upper case", "<rect ", "<Rect "),
        ("trailing digit", "<rect ", "<path2 "),
        ("space after <", "<rect ", "< rect "),
        ("prefix", "<rect ", "<svg:rect "),
        ("bare < in text", "</title>", " a < b</title>"),
    ] {
        let ids = svg_ids(&icon_with(find, replace), "app-icon");
        assert!(
            ids.contains(&(ICON_PATH.to_string(), "S-3".to_string())),
            "AC-4: {label} is S-3: {ids:?}"
        );
    }
}

/// Covers AC-4 (S-4): `viewBox` is `0 0` and two positive whole numbers
/// without leading zeros in double quotes, the namespace sits in the `svg`
/// opening tag, and only `app-icon` needs `0 0 1024 1024`.
#[test]
fn view_box_edges() {
    let view_box = "viewBox=\"0 0 1024 1024\"";
    for value in ["0 0 1 1", "0 0 300 80", "0 0 1024 1024"] {
        let text = icon_with(view_box, &format!("viewBox=\"{value}\""));
        assert_eq!(
            svg_ids(&text, "logo"),
            expect(&[]),
            "AC-4: {value} for logo"
        );
    }
    for value in [
        "0 0 0 10",
        "0 0 010 10",
        "1 0 10 10",
        "0 0  10 10",
        "0 0 10",
        "0 0 10.5 10",
        "0 0 -10 10",
    ] {
        let text = icon_with(view_box, &format!("viewBox=\"{value}\""));
        assert_eq!(
            svg_ids(&text, "logo"),
            expect(&[(ICON_PATH, "S-4")]),
            "AC-4: {value:?}"
        );
    }
    let single = icon_with(view_box, "viewBox='0 0 1024 1024'");
    assert_eq!(
        svg_ids(&single, "app-icon"),
        expect(&[(ICON_PATH, "S-4")]),
        "AC-4: quotes"
    );
    let namespace = " xmlns=\"http://www.w3.org/2000/svg\"";
    let moved = icon_with(namespace, "").replacen("<rect ", &format!("<rect{namespace} "), 1);
    assert_eq!(
        svg_ids(&moved, "app-icon"),
        expect(&[(ICON_PATH, "S-4")]),
        "AC-4: the namespace must be in the svg tag"
    );
}

/// Covers AC-4 (S-5): event attributes are found in any case and with
/// space before `=`, but not after a letter, digit, `_`, `.`, `:`, or `-`,
