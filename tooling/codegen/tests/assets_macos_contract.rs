//! Contract tests for the macOS output of the `assets` source, spec
//! `macos/0007`.
//!
//! These tests use only the public paths of `desktop_codegen` and the
//! standard library. They cover the table "Uji kontrak" in
//! `docs/specs/macos/0007-aset-merek-bersama/index.md` (AC-3): the planned
//! icon outputs, the declaration and newline rules of `svg_copy`, the
//! light and dark pair, the XML comment marker, and rule I-1 for stale
//! files in the icon document.

use std::fs;
use std::path::Path;

use desktop_codegen::assets::macos::{self, ICON_ASSETS_DIR, ICON_JSON_PATH};
use desktop_codegen::assets::{self, Asset, MANIFEST_PATH, README_PATH, SCHEMA_PATH, Variants};
use desktop_codegen::{generate, repo_root};

/// The committed `app-icon` source, from the repo root.
const ICON_SOURCE: &str = "shared/assets/source/app-icon.svg";

/// The expected `icon.json` for a `light-dark` asset, as in the spec.
const LIGHT_DARK_JSON: &str = "{\n  \"$comment\": \"Generated by desktop-codegen from tooling/codegen/src/assets/macos.rs. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- assets generate\",\n  \"groups\": [\n    {\n      \"layers\": [\n        {\n          \"image-name\": \"app-icon-light.svg\",\n          \"image-name-specializations\": [\n            {\n              \"appearance\": \"dark\",\n              \"value\": \"app-icon-dark.svg\"\n            }\n          ],\n          \"name\": \"app-icon\"\n        }\n      ]\n    }\n  ],\n  \"supported-platforms\": {\n    \"squares\": [\n      \"macOS\"\n    ]\n  }\n}\n";

/// Reads one committed file as text.
fn read(path: &str) -> String {
    fs::read_to_string(repo_root().join(path)).expect("the committed file is readable")
}

#[test]
fn committed_plan_lists_the_icon_outputs() {
    let plan = (assets::SOURCE.plan)(&repo_root()).expect("the assets are valid");
    let paths: Vec<&str> = plan
        .outputs
        .iter()
        .map(|output| output.path.as_str())
        .collect();
    assert_eq!(
        paths,
        [
            "shared/assets/brand.schema.json",
            "apps/macos/Resources/AppIcon.icon/Assets/app-icon.svg",
            "apps/macos/Resources/AppIcon.icon/icon.json",
        ]
    );
    let brand = assets::parse(&read(MANIFEST_PATH)).expect("the manifest is valid");
    let asset = brand
        .assets
        .iter()
        .find(|asset| asset.id == "app-icon")
        .expect("app-icon is listed");
    assert_eq!(plan.outputs[2].contents, macos::icon_json(asset));
    assert_eq!(
        plan.outputs[1].contents,
        macos::svg_copy(ICON_SOURCE, &read(ICON_SOURCE))
    );
    assert!(plan.outputs[2].contents.starts_with(
        "{\n  \"$comment\": \"Generated by desktop-codegen from tooling/codegen/src/assets/macos.rs. Do not edit."
    ));
}

#[test]
fn declaration_stays_on_the_first_line() {
    let marker = macos::svg_marker(ICON_SOURCE);
    let svg = "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 8 8\"/>";
    let with_declaration = macos::svg_copy(
        ICON_SOURCE,
        &format!("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n{svg}\n"),
    );
    let lines: Vec<&str> = with_declaration.lines().collect();
    assert_eq!(
        lines,
        [
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>",
            marker.as_str(),
            svg
        ]
    );
    let without = macos::svg_copy(ICON_SOURCE, &format!("{svg}\n"));
    let lines: Vec<&str> = without.lines().collect();
    assert_eq!(lines, [marker.as_str(), svg]);
}

#[test]
fn light_dark_pair_uses_the_dark_appearance() {
    let asset = Asset {
        id: "app-icon".to_string(),
        variants: Variants::LightDark,
        placeholder: false,
    };
    assert_eq!(macos::icon_json(&asset), LIGHT_DARK_JSON);
    let outputs = macos::outputs(&asset, &["<svg/>".to_string(), "<svg/>".to_string()]);
    let paths: Vec<&str> = outputs.iter().map(|output| output.path.as_str()).collect();
    assert_eq!(
        paths,
        [
            format!("{ICON_ASSETS_DIR}/app-icon-light.svg"),
            format!("{ICON_ASSETS_DIR}/app-icon-dark.svg"),
            ICON_JSON_PATH.to_string(),
        ]
    );
}

#[test]
fn marker_is_a_valid_xml_comment() {
    for source in [
        "shared/assets/source/app-icon.svg",
        "shared/assets/source/logo-dark.svg",
        "shared/assets/source/a1-b2.svg",
    ] {
        let marker = macos::svg_marker(source);
        let inner = marker
            .strip_prefix("<!--")
            .and_then(|rest| rest.strip_suffix("-->"))
            .expect("the marker is an XML comment");
        assert!(!inner.contains("--"), "{marker}");
        assert!(marker.contains("Generated by desktop-codegen"), "{marker}");
        assert!(marker.contains("Do not edit"), "{marker}");
    }
}

#[test]
fn trailing_newlines_end_in_one() {
    for contents in ["<svg/>\n\n\n", "<svg/>"] {
        let copy = macos::svg_copy(ICON_SOURCE, contents);
        assert!(copy.ends_with('\n') && !copy.ends_with("\n\n"), "{copy:?}");
        assert!(!copy.contains('\r'), "{copy:?}");
    }
}

#[test]
fn stale_icon_files_are_reported() {
    let root = Path::new(env!("CARGO_TARGET_TMPDIR")).join("assets_macos_contract_stale");
    if root.exists() {
        fs::remove_dir_all(&root).expect("the old copy can be removed");
    }
    fs::create_dir_all(root.join("shared/assets/source")).expect("the copy folder can be made");
    for path in [README_PATH, MANIFEST_PATH, SCHEMA_PATH, ICON_SOURCE] {
        fs::copy(repo_root().join(path), root.join(path)).expect("the file can be copied");
    }
    generate(&root, &assets::SOURCE).expect("generate succeeds in the copy");
    assert!(
        (assets::SOURCE.plan)(&root).is_ok(),
        "plan passes after generate"
    );

    let stale = format!("{ICON_ASSETS_DIR}/old.svg");
    fs::write(root.join(&stale), "<svg/>\n").expect("the stale file can be written");
    let problems = (assets::SOURCE.plan)(&root).expect_err("a stale file fails the plan");
    assert_eq!(problems.len(), 1, "{problems:?}");
    assert_eq!(problems[0].path, stale);
    assert!(problems[0].message.starts_with("I-1:"), "{}", problems[0]);

    fs::remove_file(root.join(&stale)).expect("the stale file can be removed");
    fs::write(root.join(format!("{ICON_ASSETS_DIR}/.DS_Store")), "")
        .expect("the system file can be written");
    assert!(
        (assets::SOURCE.plan)(&root).is_ok(),
        "ignored system files pass"
    );
    fs::remove_dir_all(&root).expect("the copy can be removed");
}
