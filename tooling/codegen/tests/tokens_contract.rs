//! Contract tests for the `tokens` source of spec `_root/0003`.
//!
//! These tests use only the public paths of `desktop_codegen`. They lock
//! the committed outputs to the generator (AC-5), the determinism of the
//! outputs (AC-6), and the resolved values in the "Nilai hasil" table of
//! `docs/specs/_root/0003-tema-bersama-dan-kontrol-native/index.md`
//! (AC-2, AC-8).

use std::fs;

use desktop_codegen::tokens::{self, Rgb, RoleName, Weight};
use desktop_codegen::{check, repo_root};

/// Reads one token file from the repo.
fn read(path: &str) -> String {
    fs::read_to_string(repo_root().join(path)).expect("the token file is readable")
}

#[test]
fn committed_outputs_match_the_source() {
    let line = check(&repo_root(), &tokens::SOURCE).unwrap_or_else(|problems| {
        let lines: Vec<String> = problems.iter().map(ToString::to_string).collect();
        panic!("tokens check failed:\n{}", lines.join("\n"))
    });
    assert!(line.starts_with("tokens: ok, "), "unexpected line: {line}");
}

#[test]
fn generation_is_deterministic() {
    let root = repo_root();
    let first = (tokens::SOURCE.plan)(&root).expect("the source is valid");
    let second = (tokens::SOURCE.plan)(&root).expect("the source is valid");
    assert_eq!(first, second);
    let absolute = root
        .canonicalize()
        .expect("the repo root exists")
        .display()
        .to_string();
    for output in &first.outputs {
        let text = &output.contents;
        assert!(text.ends_with('\n'), "{} has no final newline", output.path);
        assert!(!text.contains('\r'), "{} contains \\r", output.path);
        assert!(
            !text.contains(&absolute),
            "{} contains the repo path",
            output.path
        );
        assert!(
            text.contains("Generated by desktop-codegen"),
            "{} has no marker",
            output.path
        );
        assert!(
            text.contains("Do not edit"),
            "{} has no marker",
            output.path
        );
    }
}

#[test]
fn resolves_light_and_dark() {
    let set = tokens::parse(
        &read(tokens::COLORS_PATH),
        &read(tokens::TYPOGRAPHY_PATH),
        &read(tokens::SPACING_PATH),
    )
    .expect("the committed tokens are valid");

    let colors: Vec<(&str, Rgb, Rgb, bool)> = set
        .colors
        .iter()
        .map(|color| {
            (
                color.name.as_str(),
                color.light,
                color.dark,
                color.placeholder,
            )
        })
        .collect();
    assert_eq!(
        colors,
        [
            ("accent", Rgb(0x33, 0x66, 0xCC), Rgb(0x33, 0x66, 0xCC), true),
            (
                "background",
                Rgb(0xFA, 0xFA, 0xFA),
                Rgb(0x11, 0x11, 0x11),
                true
            ),
            (
                "text.primary",
                Rgb(0x11, 0x11, 0x11),
                Rgb(0xFA, 0xFA, 0xFA),
                true
            ),
        ]
    );

    let roles: Vec<(RoleName, Weight)> = set
        .roles
        .iter()
        .map(|role| (role.name, role.weight))
        .collect();
    assert_eq!(roles, [(RoleName::Body, Weight::Regular)]);

    let spacing: Vec<(&str, u32)> = set
        .spacing
        .iter()
        .map(|space| (space.name.as_str(), space.value))
        .collect();
    assert_eq!(spacing, [("gap.control", 12), ("inset.window", 20)]);

    assert_eq!(set.placeholders, 3);
}
