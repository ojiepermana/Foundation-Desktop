//! Rule tests for the `tokens` source of spec `_root/0003`, beyond the five
//! contract tests in `tokens_contract.rs`.
//!
//! They lock the output rules O-1 to O-6, the contrast threshold of T-8 at
//! its edge, the placeholder count (AC-8), how `parse` and `plan` collect
//! problems, that `generate` writes nothing for a broken source (AC-4), and
//! the exit codes of the command line (AC-2, AC-4). The rules live in
//! `docs/specs/_root/0003-tema-bersama-dan-kontrol-native/index.md`.
//! Broken sources are written under `env!("CARGO_TARGET_TMPDIR")`; nothing
//! under `design-system/` is edited.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use desktop_codegen::json::to_canonical_json;
use desktop_codegen::tokens::{self, Rgb};
use desktop_codegen::{Plan, Problem, check, generate, repo_root};
use serde_json::{Map, Value, json};

const GITATTRIBUTES: &str = include_str!("../../../.gitattributes");

/// The O-1 marker text of the token schemas.
const MARKER: &str = "Generated by desktop-codegen from tooling/codegen/src/tokens. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- tokens generate";

/// Reads one committed token file.
fn read(path: &str) -> String {
    fs::read_to_string(repo_root().join(path)).expect("the token file is readable")
}

/// Replaces the first `find` in `text`, failing when it is not there.
fn edit(text: &str, find: &str, replace: &str) -> String {
    assert!(text.contains(find), "search text not in file: {find:?}");
    text.replacen(find, replace, 1)
}

/// The committed text of the three token files: colors, typography, spacing.
fn sources() -> [String; 3] {
    [
        read(tokens::COLORS_PATH),
        read(tokens::TYPOGRAPHY_PATH),
        read(tokens::SPACING_PATH),
    ]
}

/// Messages of `problems` in the form `<path>: <message>`.
fn lines(problems: &[Problem]) -> Vec<String> {
    problems.iter().map(ToString::to_string).collect()
}

/// A fresh folder for one test under the Cargo target temp folder, holding
/// the given token files (path from the root, text) and nothing else.
fn temp_root(test: &str, files: &[(&str, &str)]) -> PathBuf {
    let root = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("tokens_rules_{test}"));
    if root.exists() {
        fs::remove_dir_all(&root).expect("the old copy can be removed");
    }
    fs::create_dir_all(root.join("design-system/tokens")).expect("the copy folder can be made");
    for (path, text) in files {
        fs::write(root.join(path), text).expect("the token file can be written");
    }
    root
}

/// A temp root holding the three given token files.
fn temp_root_with(test: &str, [colors, typography, spacing]: &[String; 3]) -> PathBuf {
    temp_root(
        test,
        &[
            (tokens::COLORS_PATH, colors),
            (tokens::TYPOGRAPHY_PATH, typography),
            (tokens::SPACING_PATH, spacing),
        ],
    )
}

/// The plan of the committed sources.
fn committed_plan() -> Plan {
    (tokens::SOURCE.plan)(&repo_root()).expect("the committed source is valid")
}

/// Colors with a new base `neutral.500` used as the dark value of
/// `text.primary`, so only the dark pair changes contrast.
fn colors_with_dark_text(value: &str) -> String {
    let colors = edit(
        &read(tokens::COLORS_PATH),
        "\"neutral.950\": { \"value\": \"#111111\", \"placeholder\": true }",
        &format!(
            "\"neutral.950\": {{ \"value\": \"#111111\", \"placeholder\": true }},\n    \"neutral.500\": {{ \"value\": \"{value}\" }}"
        ),
    );
    edit(
        &colors,
        "\"dark\": \"neutral.50\",\n      \"on\"",
        "\"dark\": \"neutral.500\",\n      \"on\"",
    )
}

/// Covers AC-3 (T-8): a ratio of about 4.495 is below 4.5 and fails only
/// in the appearance where it happens. The message cuts the ratio down to
/// `4.49`; rounding would print `4.50`.
#[test]
fn contrast_just_below_the_threshold_fails_with_a_cut_down_ratio() {
    let [_, typography, spacing] = sources();
    let problems = tokens::parse(&colors_with_dark_text("#6F7E85"), &typography, &spacing)
        .expect_err("4.495 is below 4.5");
    assert_eq!(
        lines(&problems),
        [
            "design-system/tokens/colors.json: semantic.text.primary: contrast on background is 4.49 in dark, needs 4.50 or more"
        ],
        "AC-3: one problem, dark only, ratio cut down"
    );
}

/// Covers AC-3 (T-8): a ratio of about 4.500004 meets the threshold.
#[test]
fn contrast_at_the_threshold_passes() {
    let [_, typography, spacing] = sources();
    let set = tokens::parse(&colors_with_dark_text("#6F7E86"), &typography, &spacing)
        .unwrap_or_else(|problems| panic!("AC-3: 4.5 passes: {:?}", lines(&problems)));
    let text = set
        .colors
        .iter()
        .find(|color| color.name == "text.primary")
        .expect("text.primary is resolved");
    assert_eq!(text.dark, Rgb(0x6F, 0x7E, 0x86), "AC-3: dark value");
}

/// Covers AC-8: placeholder flags are counted, an explicit `false` is
/// accepted, a color is flagged when either value is, and no flag ever
/// fails `check`.
#[test]
fn placeholders_are_counted_and_never_fail() {
    let [colors, typography, spacing] = sources();
    let only_brand = edit(
        &edit(
            &colors,
            "\"#FAFAFA\", \"placeholder\": true",
            "\"#FAFAFA\", \"placeholder\": false",
        ),
        "\"#111111\", \"placeholder\": true",
        "\"#111111\"",
    );
    let set = tokens::parse(&only_brand, &typography, &spacing).expect("flags are optional");
    assert_eq!(set.placeholders, 1, "AC-8: one flagged base color");
    let flagged: Vec<(&str, bool)> = set
        .colors
        .iter()
        .map(|color| (color.name.as_str(), color.placeholder))
        .collect();
    assert_eq!(
        flagged,
        [
            ("accent", true),
            ("background", false),
            ("text.primary", false)
        ],
        "AC-8: a color is flagged when either base value is"
    );

    let none = colors.replace(", \"placeholder\": true", "");
    let root = temp_root_with("placeholders", &[none, typography, spacing]);
    generate(&root, &tokens::SOURCE).expect("generate succeeds");
    let line = check(&root, &tokens::SOURCE).expect("AC-8: no flag fails check");
    assert!(
        line.contains(" semantic tokens, 0 placeholder values, "),
        "AC-8: the success line counts zero: {line}"
    );
    fs::remove_dir_all(&root).expect("the copy can be removed");
}

/// Covers AC-2 (value sourcing): the success line counts the semantic
/// tokens and placeholders `parse` returns and the outputs `plan` returns.
#[test]
fn success_line_counts_what_parse_and_plan_return() {
    let [colors, typography, spacing] = sources();
    let set = tokens::parse(&colors, &typography, &spacing).expect("committed tokens are valid");
    let line = check(&repo_root(), &tokens::SOURCE).expect("committed outputs are up to date");
    let semantic = set.colors.len() + set.roles.len() + set.spacing.len();
    let outputs = committed_plan().outputs.len();
    let parts: Vec<&str> = line.split(", ").collect();
    assert_eq!(
        parts,
        [
            "tokens: ok",
            &format!("{semantic} semantic tokens"),
            &format!("{} placeholder values", set.placeholders),
            &format!("{outputs} outputs up to date"),
        ],
        "AC-2: success line shape"
    );
}

/// Covers AC-4 (T-5): spacing accepts 128 and rejects 129.
#[test]
fn spacing_accepts_128_and_rejects_129() {
    let [colors, typography, spacing] = sources();
    let at_max = edit(&spacing, "\"value\": 20 }", "\"value\": 128 }");
    tokens::parse(&colors, &typography, &at_max).expect("AC-4: 128 is allowed");
    let over = edit(&spacing, "\"value\": 20 }", "\"value\": 129 }");
    let problems = tokens::parse(&colors, &typography, &over).expect_err("129 is too large");
    assert_eq!(
        lines(&problems),
        [
            "design-system/tokens/spacing.json: base.space.large.value: expected a whole number from 0 to 128, found 129"
        ],
        "AC-4: T-5 spacing range"
    );
}

/// Covers AC-4: `parse` collects the problems of all three files, in the
/// order colors, typography, spacing.
#[test]
fn problems_of_all_three_files_are_collected_in_file_order() {
    let [colors, typography, spacing] = sources();
    let problems = tokens::parse(
        &edit(&colors, "\"schemaVersion\": 1", "\"schemaVersion\": 2"),
        &edit(&typography, "\"body\"", "\"title\""),
        &edit(&spacing, "\"value\": 20 }", "\"value\": 129 }"),
    )
    .expect_err("all three files are broken");
    let paths: Vec<&str> = problems
        .iter()
        .map(|problem| problem.path.as_str())
        .collect();
    assert_eq!(
        paths,
        [
            tokens::COLORS_PATH,
            tokens::TYPOGRAPHY_PATH,
            tokens::SPACING_PATH
        ],
        "AC-4: one problem per file, in file order: {:?}",
        lines(&problems)
    );
}

/// Covers AC-4 and AC-7 (T-1): a file that does not fit its type gives
/// exactly one problem, and the later rules are skipped for that file.
#[test]
fn a_file_that_does_not_fit_its_type_gives_one_problem() {
    let [colors, typography, spacing] = sources();
    let broken = edit(
        &colors,
        "\"schemaVersion\": 1,",
        "\"schemaVersion\": 2, \"focus\": {},",
    );
    let problems = tokens::parse(&broken, &typography, &spacing).expect_err("unknown field");
    assert_eq!(problems.len(), 1, "AC-4: {:?}", lines(&problems));
    assert!(
        problems[0].message.contains("unknown field `focus`"),
        "AC-7: {}",
        problems[0]
    );
}

/// Covers AC-4 (plan): a token file that cannot be read gives a
/// `cannot read` problem, and `parse` is not called for the others.
#[test]
fn plan_reports_unreadable_files_without_parsing() {
    let [_, typography, spacing] = sources();
    let broken_spacing = edit(&spacing, "\"value\": 20 }", "\"value\": 129 }");
    let root = temp_root(
        "unreadable",
        &[
            (tokens::TYPOGRAPHY_PATH, &typography),
            (tokens::SPACING_PATH, &broken_spacing),
        ],
    );
    let problems = (tokens::SOURCE.plan)(&root).expect_err("colors.json is missing");
    assert_eq!(problems.len(), 1, "AC-4: {:?}", lines(&problems));
    assert_eq!(problems[0].path, tokens::COLORS_PATH);
    assert!(
        problems[0].message.starts_with("cannot read: "),
        "AC-4: {}",
        problems[0]
    );
    fs::remove_dir_all(&root).expect("the copy can be removed");
}

/// Covers AC-4: with a broken source and no outputs yet, `check` and
/// `generate` report the source and `generate` creates no file or folder.
#[test]
fn broken_source_writes_nothing_even_when_outputs_are_missing() {
    let [colors, typography, spacing] = sources();
    let broken = edit(&colors, "\"#FAFAFA\"", "\"#fafafa\"");
    let root = temp_root_with("broken", &[broken, typography, spacing]);
    for problems in [
        check(&root, &tokens::SOURCE).expect_err("the source is broken"),
        generate(&root, &tokens::SOURCE).expect_err("the source is broken"),
    ] {
        assert!(
            problems
                .iter()
                .all(|problem| problem.path == tokens::COLORS_PATH),
            "AC-4: only the source is reported: {:?}",
            lines(&problems)
        );
    }
    assert!(
        !root.join("design-system/schemas").exists(),
        "AC-4: generate wrote nothing"
    );
    fs::remove_dir_all(&root).expect("the copy can be removed");
}

/// Covers AC-4 and O-7: when one output cannot be written, `generate`
/// reports it as `cannot write` and still writes the others.
#[test]
fn generate_keeps_writing_other_outputs_when_one_fails() {
    let root = temp_root_with("unwritable", &sources());
    let plan = committed_plan();
    let blocked = &plan.outputs[0].path;
    fs::create_dir_all(root.join(blocked)).expect("a folder blocks the first output");
    let problems = generate(&root, &tokens::SOURCE).expect_err("one output cannot be written");
    assert_eq!(problems.len(), 1, "AC-4: {:?}", lines(&problems));
    assert_eq!(&problems[0].path, blocked);
    assert!(
        problems[0].message.starts_with("cannot write: "),
        "AC-4: {}",
        problems[0]
    );
    for output in &plan.outputs[1..] {
        let written = fs::read_to_string(root.join(&output.path)).expect("other outputs exist");
        assert_eq!(written, output.contents, "O-7: {} written", output.path);
    }
    fs::remove_dir_all(&root).expect("the copy can be removed");
}

