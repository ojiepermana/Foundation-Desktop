/// Covers AC-6 (O-1): the marker sits in the first three lines, and the
/// token schemas carry it as the exact `$comment` text.
#[test]
fn every_output_carries_the_marker_in_its_first_three_lines() {
    for output in committed_plan().outputs {
        let head: String = output
            .contents
            .lines()
            .take(3)
            .collect::<Vec<_>>()
            .join("\n");
        for text in ["Generated by desktop-codegen", "Do not edit"] {
            assert!(head.contains(text), "O-1: {} lacks {text:?}", output.path);
        }
        if output.path.starts_with("design-system/schemas/") {
            let value: Value = serde_json::from_str(&output.contents).expect("schema is JSON");
            assert_eq!(
                value.get("$comment").and_then(Value::as_str),
                Some(MARKER),
                "O-1: {} $comment",
                output.path
            );
        }
    }
}

/// Covers AC-6 (O-3, O-4, O-5): every JSON output is UTF-8 without BOM,
/// ends with exactly one newline, is already in canonical layout (sorted
/// keys, two space indentation), and holds whole numbers only.
#[test]
fn json_outputs_are_canonical_with_whole_numbers_and_one_final_newline() {
    fn whole_numbers_only(path: &str, value: &Value) {
        match value {
            Value::Number(number) => assert!(
                number.is_u64() || number.is_i64(),
                "O-5: {path} has {number}"
            ),
            Value::Array(items) => items.iter().for_each(|item| whole_numbers_only(path, item)),
            Value::Object(map) => map.values().for_each(|item| whole_numbers_only(path, item)),
            _ => {}
        }
    }
    for output in committed_plan()
        .outputs
        .into_iter()
        .filter(|output| output.path.ends_with(".json"))
    {
        let text = &output.contents;
        assert!(
            !text.starts_with('\u{FEFF}'),
            "O-3: {} has a BOM",
            output.path
        );
        assert!(
            text.ends_with('\n') && !text.ends_with("\n\n"),
            "O-3: {} must end with exactly one newline",
            output.path
        );
        let value: Value = serde_json::from_str(text).expect("output is JSON");
        assert_eq!(
            &to_canonical_json(&value),
            text,
            "O-4: {} is not canonical",
            output.path
        );
        whole_numbers_only(&output.path, &value);
    }
}

/// Covers AC-6 (O-6): outputs use fixed relative paths with `/`. Shared
/// ones live under `design-system/` with a per type `text eol=lf` line in
/// `.gitattributes`; the macOS tokens of spec `macos/0005` live under
/// `apps/macos/DesignSystem/` with a `text eol=lf` line for that path.
#[test]
fn outputs_live_under_design_system_with_lf_attributes() {
    let rules: Vec<&str> = GITATTRIBUTES
        .lines()
        .filter_map(|line| line.trim().strip_suffix(" text eol=lf"))
        .collect();
    for output in committed_plan().outputs {
        let path = &output.path;
        assert!(
            !path.starts_with('/') && !path.contains('\\') && !path.contains(".."),
            "O-6: {path} is a plain relative path"
        );
        let extension = path.rsplit('.').next().unwrap_or_default();
        let covered = if path.starts_with("design-system/") {
            rules.iter().any(|rule| {
                rule.starts_with("/design-system/") && rule.ends_with(&format!("*.{extension}"))
            })
        } else {
            assert!(
                path.starts_with("apps/macos/DesignSystem/"),
                "O-6: {path} location"
            );
            rules.contains(&format!("/{path}").as_str())
        };
        assert!(covered, "O-6: no text eol=lf line for {path}: {rules:?}");
    }
}

/// Covers AC-6 (O-4): `to_canonical_json` sorts keys in byte order however
/// they were inserted, keeps `serde_json` escapes, and writes empty
/// containers as `[]` and `{}`.
#[test]
fn canonical_json_sorts_keys_in_byte_order() {
    let mut inner = Map::new();
    inner.insert("z".to_string(), json!(true));
    inner.insert("y".to_string(), Value::Null);
    let mut map = Map::new();
    map.insert("n".to_string(), json!([1, Value::Object(inner)]));
    map.insert("b".to_string(), json!(1));
    map.insert("a".to_string(), json!([]));
    map.insert("B".to_string(), json!({}));
    map.insert("$c".to_string(), json!("x\"y"));
    let expected = "{\n  \"$c\": \"x\\\"y\",\n  \"B\": {},\n  \"a\": [],\n  \"b\": 1,\n  \"n\": [\n    1,\n    {\n      \"y\": null,\n      \"z\": true\n    }\n  ]\n}\n";
    assert_eq!(to_canonical_json(&Value::Object(map)), expected, "O-4");
}

/// Runs the command line with `args` and returns code, stdout, and stderr.
fn run(args: &[&str]) -> (Option<i32>, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_desktop-codegen"))
        .args(args)
        .output()
        .expect("the binary runs");
    (
        out.status.code(),
        String::from_utf8(out.stdout).expect("stdout is UTF-8"),
        String::from_utf8(out.stderr).expect("stderr is UTF-8"),
    )
}

/// Covers AC-4: a missing, unknown, or extra argument exits with code 2,
/// prints nothing to stdout, and prints the two usage lines to stderr.
#[test]
fn wrong_arguments_exit_with_2_and_two_usage_lines() {
    for args in [
        &[][..],
        &["tokens"],
        &["nope", "check"],
        &["tokens", "nope"],
        &["tokens", "check", "extra"],
    ] {
        let (code, stdout, stderr) = run(args);
        assert_eq!(code, Some(2), "AC-4: exit code for {args:?}");
        assert_eq!(stdout, "", "AC-4: no stdout for {args:?}");
        let usage: Vec<&str> = stderr.lines().collect();
        assert_eq!(
            usage.len(),
            2,
            "AC-4: two usage lines for {args:?}: {stderr}"
        );
        assert_eq!(usage[0], "usage: desktop-codegen <source> <check|generate>");
        assert!(
            usage[1].starts_with("sources: ") && usage[1].contains("tokens"),
            "AC-4: sources line for {args:?}: {}",
            usage[1]
        );
    }
}

/// Covers AC-2: `tokens check` on the repo exits with 0 and prints exactly
/// the success line of `check` to stdout, and nothing to stderr.
#[test]
fn tokens_check_exits_with_0_and_one_success_line() {
    let (code, stdout, stderr) = run(&["tokens", "check"]);
    let line = check(&repo_root(), &tokens::SOURCE).expect("committed outputs are up to date");
    assert_eq!(code, Some(0), "AC-2: exit code, stderr: {stderr}");
    assert_eq!(stdout, format!("{line}\n"), "AC-2: one success line");
    assert_eq!(stderr, "", "AC-2: nothing on stderr");
}
