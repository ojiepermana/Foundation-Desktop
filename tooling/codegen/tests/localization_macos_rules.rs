//! Rule tests for the macOS output of the `localization` source, spec
//! `macos/0006`, beyond the seven cases in `localization_macos_contract.rs`.
//!
//! They lock the escaping rule at its edges (combinations, text that looks
//! like a format, no double escaping, non ASCII kept), positional
//! placeholders for several and repeated names, one file per locale in
//! catalog order with folders named after the locale, fallback comments
//! for many keys and locales, the shape for a catalog without entries, how
//! `plan` carries the files, and the `generate` and `check` round trip.
//! The rules live in
//! `docs/specs/macos/0006-satu-contoh-lokalisasi/index.md`. Test catalogs
//! are built in the test and written only under
//! `env!("CARGO_TARGET_TMPDIR")`; nothing under `shared/` or `apps/macos/`
//! is edited.

use std::fs;
use std::path::{Path, PathBuf};

use desktop_codegen::localization::macos::{RESOURCES_DIR, outputs};
use desktop_codegen::localization::{self, CATALOG_PATH, Catalog, SCHEMA_PATH};
use desktop_codegen::{Output, check, generate, repo_root};
use serde_json::{Value, json};

/// The first line of every `.strings` file ("Bentuk berkas" item 1).
const MARKER: &str = "/* Generated by desktop-codegen from tooling/codegen/src/localization. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- localization generate */";

/// A catalog with a valid header and the given locales, source, and entries.
fn catalog_text(locales: &[&str], source: &str, entries: Value) -> String {
    serde_json::to_string_pretty(&json!({
        "$schema": "./catalog.schema.json",
        "schemaVersion": localization::SCHEMA_VERSION,
        "sourceLocale": source,
        "locales": locales,
        "entries": entries,
    }))
    .expect("the catalog serializes")
}

/// Parses `text` or fails with every problem.
fn parse(text: &str) -> Catalog {
    localization::parse(text).unwrap_or_else(|problems| {
        let lines: Vec<String> = problems.iter().map(ToString::to_string).collect();
        panic!("the test catalog must be valid:\n{}", lines.join("\n"))
    })
}

/// One entry with a valid description and the given texts.
fn entry(texts: Value) -> Value {
    json!({ "description": "A label.", "text": texts })
}

/// The path of the file for `locale`.
fn path(locale: &str) -> String {
    format!("{RESOURCES_DIR}/{locale}.lproj/Localizable.strings")
}

/// The file for `locale` among `files`.
fn file<'a>(files: &'a [Output], locale: &str) -> &'a str {
    let wanted = path(locale);
    &files
        .iter()
        .find(|output| output.path == wanted)
        .unwrap_or_else(|| panic!("no file for {locale}"))
        .contents
}

/// The `"key" = "value";` lines of a file, in order.
fn pairs(text: &str) -> Vec<&str> {
    text.lines().filter(|line| line.starts_with('"')).collect()
}

/// Covers AC-2 and AC-6 ("Bentuk berkas" item 4): `\`, `"`, and `%` are
/// escaped once each, in any combination and order, text that looks like a
/// format or an escape stays plain, and non ASCII text is kept.
#[test]
fn escaping_edges() {
    let cases = [
        (r#"a\"b"#, r#"a\\\"b"#),
        (r"\\", r"\\\\"),
        ("%%", "%%%%"),
        (r"\%", r"\\%%"),
        (r#""%""#, r#"\"%%\""#),
        ("%1$@ %@ %d", "%%1$@ %%@ %%d"),
        (r"\n \t", r"\\n \\t"),
        (
            "Łukasz 李 \u{1F469}\u{200D}\u{1F4BB} é",
            "Łukasz 李 \u{1F469}\u{200D}\u{1F4BB} é",
        ),
        ("* _ < > & ' /", "* _ < > & ' /"),
    ];
    for (input, expected) in cases {
        let files = outputs(&parse(&catalog_text(
            &["en"],
            "en",
            json!({ "a.b": entry(json!({ "en": input })) }),
        )));
        assert_eq!(
            pairs(file(&files, "en")),
            [format!("\"a.b\" = \"{expected}\";")],
            "AC-6: {input:?}"
        );
    }
}

/// Covers AC-2 (L-7): placeholder numbers follow `Entry.placeholders`, the
/// order of first appearance in the source text, not the order in a
/// translation; a repeated name keeps its number; placeholders sit next to
/// escaped characters without merging.
#[test]
fn placeholders_follow_the_source_order() {
    let catalog = parse(&catalog_text(
        &["en", "id"],
        "en",
        json!({
            "a.b": entry(json!({ "en": "{a} {b} {c}", "id": "{c} {a} {c} {b}" })),
            "a.c": entry(json!({ "en": "%{x}% \"{y}\"", "id": "{y}{x}" })),
        }),
    ));
    let files = outputs(&catalog);
    assert_eq!(
        pairs(file(&files, "en")),
        [
            "\"a.b\" = \"%1$@ %2$@ %3$@\";",
            "\"a.c\" = \"%%%1$@%% \\\"%2$@\\\"\";",
        ],
        "AC-2: source"
    );
    assert_eq!(
        pairs(file(&files, "id")),
        [
            "\"a.b\" = \"%3$@ %1$@ %3$@ %2$@\";",
            "\"a.c\" = \"%2$@%1$@\";"
        ],
        "AC-2: translation keeps the source numbers"
    );
}

/// Covers AC-1 and AC-2 (OS-2): one file per locale in the order of
/// `locales`, each folder named after its locale, keys in byte order, and
/// the same bytes on every call.
#[test]
fn one_file_per_locale_in_catalog_order() {
    let locales = ["zh-TW", "en", "pt-BR", "fil"];
    let texts = json!({ "en": "B", "zh-TW": "B", "pt-BR": "B", "fil": "B" });
    let catalog = parse(&catalog_text(
        &locales,
        "en",
        json!({ "b.second": entry(texts.clone()), "a.first": entry(texts) }),
    ));
    let first = outputs(&catalog);
    assert_eq!(first, outputs(&catalog), "AC-2: deterministic");
    let paths: Vec<String> = first.iter().map(|output| output.path.clone()).collect();
    let expected: Vec<String> = locales.iter().map(|locale| path(locale)).collect();
    assert_eq!(
        paths, expected,
        "AC-1: one file per locale, in catalog order"
    );
    for output in &first {
        let keys: Vec<&str> = pairs(&output.contents)
            .iter()
            .map(|line| line.split('"').nth(1).expect("a key"))
            .collect();
        assert_eq!(keys, ["a.first", "b.second"], "AC-2: keys in byte order");
    }
}

/// Covers AC-2 (L-9, "Bentuk berkas" item 2): with three keys and four
/// locales, the source not first, every fallback text is the escaped
/// source text with a comment naming the locale and the source, and only
/// fallback texts have that comment.
#[test]
fn missing_translations_are_marked_in_every_file() {
    let catalog = parse(&catalog_text(
        &["id", "en", "ms", "pt-BR"],
        "en",
        json!({
            "b.title": entry(json!({ "en": "50% \"off\"", "id": "Judul" })),
            "a.hint": entry(json!({ "en": "Hint", "ms": "Petua", "pt-BR": "Dica" })),
            "c.ok": entry(json!({ "en": "OK", "id": "Oke", "ms": "Okey", "pt-BR": "Certo" })),
        }),
    ));
    let files = outputs(&catalog);
    let expected = [
        ("id", vec!["a.hint"]),
        ("en", vec![]),
        ("ms", vec!["b.title"]),
        ("pt-BR", vec!["b.title"]),
    ];
    for (locale, missing) in expected {
        let text = file(&files, locale);
        let comment = format!("/* Missing translation for {locale}, shows the en text. */");
        assert_eq!(
            text.matches(&comment).count(),
            missing.len(),
            "AC-2: {locale} fallback comments"
        );
        for key in missing {
            let source = if key == "b.title" {
                "50%% \\\"off\\\""
            } else {
                "Hint"
            };
            let block = format!("{comment}\n\"{key}\" = \"{source}\";\n");
            assert!(
                text.contains(&block),
                "AC-2: {locale} {key} falls back to the source text"
            );
        }
        assert!(
            !text.contains("Missing translation for en"),
            "AC-2: the source never falls back"
        );
    }
}

/// Covers AC-2 ("Bentuk berkas" items 1 and 3): a catalog without entries
/// gives files that hold only the marker line, and every file starts with
/// the marker, uses LF, and ends with one newline.
#[test]
fn catalog_without_entries_gives_only_the_marker() {
    let files = outputs(&parse(&catalog_text(&["en", "id"], "en", json!({}))));
    assert_eq!(files.len(), 2, "AC-1: one file per locale");
    for output in &files {
        assert_eq!(
            output.contents,
            format!("{MARKER}\n"),
            "AC-2: {}",
            output.path
        );
    }
}

/// Covers AC-1 (OS-2): the committed plan holds the schema first, then one
/// file per catalog locale in that order, built from the parsed catalog.
#[test]
fn plan_carries_one_file_per_locale_after_the_schema() {
    let text = fs::read_to_string(repo_root().join(CATALOG_PATH)).expect("readable");
    let catalog = parse(&text);
    let plan = (localization::SOURCE.plan)(&repo_root()).expect("the committed catalog is valid");
    assert_eq!(plan.outputs[0].path, SCHEMA_PATH, "AC-1: schema first");
    let strings: Vec<&Output> = plan
        .outputs
        .iter()
        .filter(|output| output.path.starts_with(&format!("{RESOURCES_DIR}/")))
        .collect();
    let expected = outputs(&catalog);
    assert_eq!(
        strings.len(),
        catalog.locales.len(),
        "AC-1: one file per locale"
    );
    for (planned, built) in strings.iter().zip(&expected) {
        assert_eq!(*planned, built, "AC-1: built from the parsed catalog");
    }
}

/// A fresh `localization_macos_rules_<test>` root holding the committed
/// catalog and nothing else.
fn temp_root(test: &str) -> PathBuf {
    let root =
        Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("localization_macos_rules_{test}"));
    if root.exists() {
        fs::remove_dir_all(&root).expect("the old copy can be removed");
    }
    let catalog = root.join(CATALOG_PATH);
    fs::create_dir_all(catalog.parent().expect("a parent")).expect("the folder can be made");
    fs::copy(repo_root().join(CATALOG_PATH), &catalog).expect("the catalog is copied");
    root
}

/// Covers AC-1: in a fresh root `generate` makes the `.lproj` folders and
/// writes every planned file, `check` passes, a hand edit of one file is
/// reported as that file only, and `generate` rewrites only it.
#[test]
fn generate_and_check_round_trip_for_the_strings_files() {
    let root = temp_root("round_trip");
    let (written, _) = generate(&root, &localization::SOURCE).expect("generate succeeds");
    let plan = (localization::SOURCE.plan)(&root).expect("valid");
    for output in &plan.outputs {
        assert!(
            written.contains(&output.path),
            "AC-1: wrote {}",
            output.path
        );
        let on_disk = fs::read_to_string(root.join(&output.path)).expect("written");
        assert_eq!(on_disk, output.contents, "AC-1: {} as planned", output.path);
    }
    check(&root, &localization::SOURCE).expect("AC-1: check passes");

    let edited = plan
        .outputs
        .iter()
        .find(|output| output.path.starts_with(&format!("{RESOURCES_DIR}/")))
        .expect("a strings file");
    fs::write(root.join(&edited.path), format!("{}\n", edited.contents)).expect("editable");
    let problems = check(&root, &localization::SOURCE).expect_err("a hand edit is caught");
    assert_eq!(problems.len(), 1, "AC-1: {problems:?}");
    assert_eq!(problems[0].path, edited.path);
    assert!(
        problems[0]
            .message
            .starts_with("differs from the generator output"),
        "AC-1: {}",
        problems[0]
    );
    let (written, _) = generate(&root, &localization::SOURCE).expect("generate succeeds");
    assert_eq!(written, [edited.path.clone()], "AC-1: only the edited file");
    fs::remove_dir_all(&root).expect("the copy can be removed");
}
