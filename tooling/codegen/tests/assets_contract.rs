#[test]
fn rejects_wrong_folder_contents() {
    let mut failures = Vec::new();
    for (number, rule) in WRONG_FOLDERS {
        let root = folder_case(number);
        let found = messages((assets::SOURCE.plan)(&root));
        let prefix = format!("{rule}: ");
        if !found.iter().any(|message| message.starts_with(&prefix)) {
            failures.push(format!(
                "{number}: expected a {rule} problem, got {found:?}"
            ));
        }
        fs::remove_dir_all(&root).expect("the fixture can be removed");
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn accepts_valid_sources() {
    let manifest = read(MANIFEST_PATH);

    // M-15 to M-17.
    let brand = assets::parse(&manifest).expect("M-15 is valid");
    assert_eq!((brand.assets.len(), brand.placeholders), (1, 1), "M-15");
    let brand = assets::parse(&replaced(&manifest, ",\n      \"placeholder\": true", ""))
        .expect("M-16 is valid");
    assert!(!brand.assets[0].placeholder, "M-16");
    assert_eq!(brand.placeholders, 0, "M-16");
    let brand = assets::parse(&replaced(
        &manifest,
        "\"assets\": {",
        "\"assets\": {\n    \"logo\": {\n      \"variants\": \"light-dark\"\n    },",
    ))
    .expect("M-17 is valid");
    let ids: Vec<&str> = brand.assets.iter().map(|asset| asset.id.as_str()).collect();
    assert_eq!(ids, ["app-icon", "logo"], "M-17");
    assert_eq!(
        brand.assets[1].source_paths(),
        [
            "shared/assets/source/logo-light.svg",
            "shared/assets/source/logo-dark.svg"
        ],
        "M-17"
    );

    // S-28 to S-31.
    let icon = read(ICON_PATH);
    let sources = [
        ("S-28", icon.clone(), "app-icon"),
        (
            "S-29",
            format!(
                "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- catatan <script> -->\n{icon}"
            ),
            "app-icon",
        ),
        (
            "S-30",
            replaced(
                &icon,
                "</svg>",
                "<defs><linearGradient id=\"g\"><stop offset=\"0\" stop-color=\"#fff\"/></linearGradient></defs><rect fill=\"url(#g)\"/><rect fill=\"url('#g')\"/><use href=\"#g\"/><desc>catatan &amp; keterangan</desc></svg>",
            ),
            "app-icon",
        ),
        (
            "S-31",
            replaced(&icon, "viewBox=\"0 0 1024 1024\"", "viewBox=\"0 0 300 80\""),
            "logo",
        ),
    ];
    for (number, text, id) in &sources {
        let found = assets::check_svg(ICON_PATH, id, text.as_bytes());
        assert!(found.is_empty(), "{number}: {found:?}");
    }

    // F-14 to F-17.
    for (number, summary) in [
        ("F-14", "1 assets, 1 source files, 1 placeholder values"),
        ("F-15", "1 assets, 1 source files, 1 placeholder values"),
        ("F-16", "1 assets, 1 source files, 1 placeholder values"),
        ("F-17", "1 assets, 2 source files, 1 placeholder values"),
    ] {
        let root = folder_case(number);
        let plan = (assets::SOURCE.plan)(&root)
            .unwrap_or_else(|problems| panic!("{number}: {problems:?}"));
        assert_eq!(plan.summary, summary, "{number}");
        fs::remove_dir_all(&root).expect("the fixture can be removed");
    }
}
