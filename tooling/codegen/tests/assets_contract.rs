#[test]
fn rejects_broken_svgs() {
    let mut failures = Vec::new();
    for (number, change, rules) in &BROKEN_SVGS {
        let found: Vec<String> = assets::check_svg(ICON_PATH, "app-icon", &changed_icon(change))
            .iter()
            .map(|problem| problem.message.clone())
            .collect();
        for rule in *rules {
            let prefix = format!("{rule}: ");
            if !found.iter().any(|message| message.starts_with(&prefix)) {
                failures.push(format!(
                    "{number}: expected a {rule} problem, got {found:?}"
                ));
            }
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// Makes `assets_contract_<name>` under the target temp folder. With
/// `copy`, it holds a copy of the four committed files under
/// `shared/assets/`.
fn fixture(name: &str, copy: bool) -> PathBuf {
    let root = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("assets_contract_{name}"));
    if root.exists() {
        fs::remove_dir_all(&root).expect("the old fixture can be removed");
    }
    fs::create_dir_all(&root).expect("the fixture root can be made");
    if copy {
        fs::create_dir_all(root.join(SOURCE_DIR)).expect("the fixture folders can be made");
        for path in [README_PATH, MANIFEST_PATH, SCHEMA_PATH, ICON_PATH] {
            fs::copy(repo_root().join(path), root.join(path)).expect("the file can be copied");
        }
    }
    root
}

/// Writes `contents` to `path` under `root`.
fn write(root: &Path, path: &str, contents: &str) {
    fs::write(root.join(path), contents).expect("the fixture file can be written");
}

/// Changes the manifest of the fixture from `any` to `light-dark`.
fn make_light_dark(root: &Path) {
    let manifest = read(MANIFEST_PATH);
    write(
        root,
        MANIFEST_PATH,
        &replaced(
            &manifest,
            "\"variants\": \"any\"",
            "\"variants\": \"light-dark\"",
        ),
    );
}

/// Builds the fixture for one folder case.
fn folder_case(number: &str) -> PathBuf {
    let name = number.replace('-', "").to_lowercase();
    let root = fixture(&name, number != "F-6");
    let remove_file =
        |path: &str| fs::remove_file(root.join(path)).expect("the file can be removed");
    match number {
        "F-1" => write(&root, "shared/assets/notes.txt", "x"),
        "F-2" => fs::create_dir(root.join("shared/assets/export")).expect("the folder can be made"),
        "F-3" => remove_file(README_PATH),
        "F-4" => remove_file(MANIFEST_PATH),
        "F-5" => fs::remove_dir_all(root.join(SOURCE_DIR)).expect("the folder can be removed"),
        "F-6" => {}
        "F-7" => {
            remove_file(MANIFEST_PATH);
            fs::create_dir(root.join(MANIFEST_PATH)).expect("the folder can be made");
        }
        "F-8" => write(&root, "shared/assets/source/logo.svg", &read(ICON_PATH)),
        "F-9" => remove_file(ICON_PATH),
        "F-10" => {
            fs::create_dir(root.join("shared/assets/source/old")).expect("the folder can be made")
        }
        "F-11" => write(&root, "shared/assets/source/app-icon.png", "x"),
        "F-12" => make_light_dark(&root),
        "F-13" => write(
            &root,
            ICON_PATH,
            &replaced(&read(ICON_PATH), "</svg>", "<script/></svg>"),
        ),
        "F-14" => {}
        "F-15" => {
            for folder in [DIR, SOURCE_DIR] {
                for name in [".DS_Store", "Thumbs.db", "desktop.ini"] {
                    write(&root, &format!("{folder}/{name}"), "");
                }
            }
        }
        "F-16" => remove_file(SCHEMA_PATH),
        "F-17" => {
            make_light_dark(&root);
            remove_file(ICON_PATH);
            for path in [
                "shared/assets/source/app-icon-light.svg",
                "shared/assets/source/app-icon-dark.svg",
            ] {
                write(&root, path, &read(ICON_PATH));
            }
        }
        other => panic!("unknown folder case {other}"),
    }
    root
}

