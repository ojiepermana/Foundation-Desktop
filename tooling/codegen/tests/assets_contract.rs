#[test]
fn rejects_broken_manifests() {
    let manifest = read(MANIFEST_PATH);
    let mut failures = Vec::new();
    for (number, find, replace) in BROKEN_MANIFESTS {
        let text = if find.is_empty() {
            replace.to_string()
        } else {
            replaced(&manifest, find, replace)
        };
        let found = messages(assets::parse(&text));
        if !found.iter().any(|message| message.starts_with("A-2: ")) {
            failures.push(format!("{number}: expected an A-2 problem, got {found:?}"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// How a source case changes the committed `app-icon.svg`.
enum Change {
    /// Replace the first `.0` with `.1`.
    Replace(&'static str, &'static str),
    /// Put the text in front of the file.
    Prefix(&'static str),
    /// Replace the first new line with `\r\n`.
    CarriageReturn,
    /// Put a byte order mark in front of the file.
    ByteOrderMark,
    /// Append a comment that makes the file too large.
    TooLarge,
    /// Use five bytes that are not UTF-8.
    NotUtf8,
}

/// Applies `change` to the committed `app-icon.svg`.
fn changed_icon(change: &Change) -> Vec<u8> {
    let icon = read(ICON_PATH);
    match change {
        Change::Replace(find, replace) => replaced(&icon, find, replace).into_bytes(),
        Change::Prefix(prefix) => format!("{prefix}{icon}").into_bytes(),
        Change::CarriageReturn => replaced(&icon, "\n", "\r\n").into_bytes(),
        Change::ByteOrderMark => format!("\u{feff}{icon}").into_bytes(),
        Change::TooLarge => format!("{icon}<!--{}-->\n", "a".repeat(262_144)).into_bytes(),
        Change::NotUtf8 => vec![0xFF, 0xFE, 0x3C, 0x00, 0x73],
    }
}

