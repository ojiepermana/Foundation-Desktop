//! Contract tests for the `assets` source of spec `_root/0005`.
//!
//! These tests use only the public paths of `desktop_codegen` and the
//! standard library. They lock the committed schema to the generator
//! (AC-5), the committed manifest (AC-3), and every row of the manifest
//! cases M-1 to M-17, the source cases S-1 to S-31, and the folder cases
//! F-1 to F-17 in `docs/specs/_root/0005-aset-merek-bersama/index.md`
//! (AC-4). Folder cases run on a copy under a temporary root and never
//! edit `shared/assets/` itself.

use std::fs;
use std::path::{Path, PathBuf};

use desktop_codegen::assets::{
    self, DIR, MANIFEST_PATH, README_PATH, SCHEMA_PATH, SOURCE_DIR, Variants,
};
use desktop_codegen::{check, repo_root};

/// The committed `app-icon` source, from the repo root.
const ICON_PATH: &str = "shared/assets/source/app-icon.svg";

/// Reads one committed file as text.
fn read(path: &str) -> String {
    fs::read_to_string(repo_root().join(path)).expect("the committed file is readable")
}

/// Replaces the first `find` with `replace` in `text`.
fn replaced(text: &str, find: &str, replace: &str) -> String {
    assert!(text.contains(find), "{find:?} is not in the text");
    text.replacen(find, replace, 1)
}

/// The problem messages of a failed result, or `(accepted)`.
fn messages<T>(result: Result<T, Vec<desktop_codegen::Problem>>) -> Vec<String> {
    match result {
        Ok(_) => vec!["(accepted)".to_string()],
        Err(problems) => problems
            .iter()
            .map(|problem| problem.message.clone())
            .collect(),
    }
}

#[test]
fn committed_outputs_match_the_source() {
    let line = check(&repo_root(), &assets::SOURCE).unwrap_or_else(|problems| {
        let lines: Vec<String> = problems.iter().map(ToString::to_string).collect();
        panic!("assets check failed:\n{}", lines.join("\n"))
    });
    assert!(line.starts_with("assets: ok, "), "unexpected line: {line}");
}

#[test]
fn generation_is_deterministic() {
    let root = repo_root();
    let first = (assets::SOURCE.plan)(&root).expect("the assets are valid");
    let second = (assets::SOURCE.plan)(&root).expect("the assets are valid");
    assert_eq!(first, second);
    let absolute = root
        .canonicalize()
        .expect("the repo root exists")
        .display()
        .to_string();
    for output in &first.outputs {
        let text = &output.contents;
        assert!(text.ends_with('\n'), "{} has no final newline", output.path);
        assert!(!text.contains('\r'), "{} contains \\r", output.path);
        assert!(
            !text.contains(&absolute),
            "{} contains the repo path",
            output.path
        );
        assert!(
            text.contains("Generated by desktop-codegen"),
            "{} has no marker",
            output.path
        );
        assert!(
            text.contains("Do not edit"),
            "{} has no marker",
            output.path
        );
    }
}

#[test]
fn reads_the_committed_brand() {
    let brand = assets::parse(&read(MANIFEST_PATH)).expect("the committed manifest is valid");
    assert_eq!(brand.assets.len(), 1);
    let asset = &brand.assets[0];
    assert_eq!(asset.id, "app-icon");
    assert_eq!(asset.variants, Variants::Any);
    assert!(asset.placeholder);
    assert_eq!(brand.placeholders, 1);
    assert_eq!(asset.source_paths(), ["shared/assets/source/app-icon.svg"]);
}

