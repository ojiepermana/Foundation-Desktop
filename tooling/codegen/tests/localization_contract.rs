//! Contract tests for the `localization` source of spec `_root/0006`.
//!
//! These tests use only the public paths of `desktop_codegen`. "The real
//! catalog" means the text of `shared/localization/catalog.json` read when
//! the test runs. They lock the committed schema to the generator (AC-9),
//! a complete committed catalog (AC-6), and the resolved values in the
//! "Nilai hasil" table of
//! `docs/specs/_root/0006-satu-contoh-lokalisasi/index.md` (AC-2, AC-7).
//! They also run the test catalogs K-1 and K-2 (AC-5, AC-6, AC-7) and the
//! 31 rows of the "Kasus sumber rusak" table (AC-3, AC-4, AC-5, AC-8).

use std::fs;
use std::path::Path;

use desktop_codegen::localization::{self, Catalog, Origin};
use desktop_codegen::{check, repo_root};

/// Reads the real catalog.
fn real_catalog() -> String {
    fs::read_to_string(repo_root().join(localization::CATALOG_PATH))
        .expect("the catalog is readable")
}

/// Parses `text` or fails with every problem.
fn parse_ok(text: &str) -> Catalog {
    localization::parse(text).unwrap_or_else(|problems| {
        let lines: Vec<String> = problems.iter().map(ToString::to_string).collect();
        panic!("parse failed:\n{}", lines.join("\n"))
    })
}

/// The `(locale, value, origin)` triples of the entry at `index`.
fn texts(catalog: &Catalog, index: usize) -> Vec<(&str, &str, Origin)> {
    catalog.entries[index]
        .texts
        .iter()
        .map(|text| (text.locale.as_str(), text.value.as_str(), text.origin))
        .collect()
}

#[test]
fn committed_outputs_match_the_source() {
    let line = check(&repo_root(), &localization::SOURCE).unwrap_or_else(|problems| {
        let lines: Vec<String> = problems.iter().map(ToString::to_string).collect();
        panic!("localization check failed:\n{}", lines.join("\n"))
    });
    assert!(
        line.starts_with("localization: ok, "),
        "unexpected line: {line}"
    );
}

#[test]
fn committed_catalog_is_complete() {
    let catalog = parse_ok(&real_catalog());
    let missing: Vec<String> = catalog
        .missing
        .iter()
        .map(|missing| format!("{} {}", missing.key, missing.locale))
        .collect();
    assert!(
        missing.is_empty(),
        "missing translations: {}",
        missing.join("; ")
    );
}

#[test]
fn real_catalog_resolves() {
    let catalog = parse_ok(&real_catalog());
    assert_eq!(catalog.source_locale, "en");
    assert_eq!(catalog.locales, ["en", "id"]);
    assert_eq!(catalog.entries.len(), 1);
    let entry = &catalog.entries[0];
    assert_eq!(entry.key, "greeting.submit");
    assert!(entry.placeholders.is_empty());
    assert_eq!(
        texts(&catalog, 0),
        [("en", "Greet", Origin::Own), ("id", "Sapa", Origin::Own)]
    );
    assert!(catalog.missing.is_empty());
}

#[test]
fn generation_is_deterministic() {
    let root = repo_root();
    let first = (localization::SOURCE.plan)(&root).expect("the catalog is valid");
    let second = (localization::SOURCE.plan)(&root).expect("the catalog is valid");
    assert_eq!(first, second);
    let absolute = root
        .canonicalize()
        .expect("the repo root exists")
        .display()
        .to_string();
    for output in &first.outputs {
        let text = &output.contents;
        assert!(text.ends_with('\n'), "{} has no final newline", output.path);
        assert!(!text.contains('\r'), "{} contains \\r", output.path);
        assert!(
            !text.contains(&absolute),
            "{} contains the repo path",
            output.path
        );
        assert!(
            text.contains("Generated by desktop-codegen"),
            "{} has no marker",
            output.path
        );
        assert!(
            text.contains("Do not edit"),
            "{} has no marker",
            output.path
        );
    }
}

/// Replaces the first `find` with `replace` in the real catalog.
fn edited(find: &str, replace: &str) -> String {
    let text = real_catalog();
    assert!(text.contains(find), "{find:?} is not in the real catalog");
    text.replacen(find, replace, 1)
}

/// Test catalog K-1: placeholders in a different order per locale.
fn catalog_k1() -> String {
    edited("\"Greet\"", "\"{name}, welcome to {app}.\"").replacen(
        "\"Sapa\"",
        "\"Selamat datang di {app}, {name}.\"",
        1,
    )
}

/// Test catalog K-2: a third locale and no `id` text.
fn catalog_k2() -> String {
    edited("[\"en\", \"id\"]", "[\"en\", \"id\", \"ms\"]").replacen(
        "\"Greet\",\n        \"id\": \"Sapa\"",
        "\"Greet\"",
        1,
    )
}

#[test]
fn placeholders_may_reorder() {
    let catalog = parse_ok(&catalog_k1());
    assert_eq!(catalog.entries.len(), 1);
    assert_eq!(catalog.entries[0].placeholders, ["name", "app"]);
    let origins: Vec<Origin> = catalog.entries[0]
        .texts
        .iter()
        .map(|text| text.origin)
        .collect();
    assert_eq!(origins, [Origin::Own, Origin::Own]);
    assert!(catalog.missing.is_empty());
}

#[test]
fn missing_translations_are_listed_and_fall_back() {
    let text = catalog_k2();
    let catalog = parse_ok(&text);
    assert_eq!(catalog.locales, ["en", "id", "ms"]);
    assert_eq!(
        texts(&catalog, 0),
        [
            ("en", "Greet", Origin::Own),
            ("id", "Greet", Origin::Fallback),
            ("ms", "Greet", Origin::Fallback),
        ]
    );
    let missing: Vec<(&str, &str)> = catalog
        .missing
        .iter()
        .map(|missing| (missing.key.as_str(), missing.locale.as_str()))
        .collect();
    assert_eq!(
        missing,
        [("greeting.submit", "id"), ("greeting.submit", "ms")]
    );

    let root = Path::new(env!("CARGO_TARGET_TMPDIR")).join("localization_contract_k2");
    if root.exists() {
        fs::remove_dir_all(&root).expect("the old copy can be removed");
    }
    let path = root.join(localization::CATALOG_PATH);
    fs::create_dir_all(path.parent().expect("the catalog has a folder"))
        .expect("the copy folder can be made");
    fs::write(&path, &text).expect("the catalog can be copied");
    let plan = (localization::SOURCE.plan)(&root).expect("K-2 is valid");
    assert_eq!(
        plan.summary,
        "1 keys, 3 locales, 2 missing translations (greeting.submit id; greeting.submit ms)"
    );
    fs::remove_dir_all(&root).expect("the copy can be removed");
}

