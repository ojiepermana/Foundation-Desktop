/// Covers AC-4 (O-1, O-3 to O-6 of spec `_root/0003`): every planned
/// output carries the marker in its first three lines, is UTF-8 without
/// BOM with one final newline, uses a relative `/` path under
/// `shared/config/` or an app folder, and has a per type `text eol=lf`
/// line. JSON outputs are canonical with whole numbers only, and the
/// shared schema's `$comment` is the exact marker.
#[test]
fn every_output_follows_the_output_rules() {
    fn whole_numbers_only(path: &str, value: &Value) {
        match value {
            Value::Number(number) => {
                assert!(
                    number.is_u64() || number.is_i64(),
                    "O-5: {path} has {number}"
                );
            }
            Value::Array(items) => items.iter().for_each(|item| whole_numbers_only(path, item)),
            Value::Object(map) => map.values().for_each(|item| whole_numbers_only(path, item)),
            _ => {}
        }
    }
    let rules: Vec<&str> = GITATTRIBUTES
        .lines()
        .filter_map(|line| line.trim().strip_suffix(" text eol=lf"))
        .collect();
    for output in committed_plan().outputs {
        let (path, text) = (output.path.as_str(), output.contents.as_str());
        let head = text.lines().take(3).collect::<Vec<_>>().join("\n");
        for marker in ["Generated by desktop-codegen", "Do not edit"] {
            assert!(head.contains(marker), "O-1: {path} lacks {marker:?}");
        }
        assert!(!text.starts_with('\u{feff}'), "O-3: {path} has a BOM");
        assert!(
            text.ends_with('\n') && !text.ends_with("\n\n") && !text.contains('\r'),
            "O-3: {path} line endings"
        );
        assert!(
            !path.starts_with('/') && !path.contains('\\') && !path.contains(".."),
            "O-6: {path} is a plain relative path"
        );
        assert!(
            path.starts_with("shared/config/") || path.starts_with("apps/"),
            "O-6: {path} lives in the source folder or an app folder"
        );
        let top = path.split('/').next().unwrap_or_default();
        let extension = path.rsplit('.').next().unwrap_or_default();
        assert!(
            rules
                .iter()
                .any(|rule| rule.starts_with(&format!("/{top}/"))
                    && rule.ends_with(&format!("*.{extension}"))),
            "O-6: no per type text eol=lf line for {path}: {rules:?}"
        );
        if path.ends_with(".json") {
            let value: Value = serde_json::from_str(text).expect("output is JSON");
            assert_eq!(
                to_canonical_json(&value),
                text,
                "O-4: {path} is not canonical"
            );
            whole_numbers_only(path, &value);
            if path.starts_with("shared/config/") {
                assert_eq!(
                    value["$comment"].as_str(),
                    Some(MARKER),
                    "O-1: {path} $comment"
                );
            }
        }
    }
}

/// Returns every `.swift` file under `dir`, skipping build output.
fn swift_files(dir: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let mut pending = vec![dir.to_path_buf()];
    while let Some(folder) = pending.pop() {
        let Ok(entries) = fs::read_dir(&folder) else {
            continue;
        };
        for entry in entries {
            let path = entry.expect("entry").path();
            let name = path
                .file_name()
                .and_then(|n| n.to_str())
                .unwrap_or_default();
            if path.is_dir() && !path.is_symlink() {
                if ![".build", "DerivedData"].contains(&name) {
                    pending.push(path);
                }
            } else if name.ends_with(".swift") {
                found.push(path);
            }
        }
    }
    found
}

/// Covers K-3: no Swift source names `shared/config` or `public.json`, so
/// the app never opens the shared config folder at run time. Build time
/// copies come from the generator.
#[test]
fn swift_sources_never_open_the_shared_config() {
    for path in swift_files(&repo_root().join("apps")) {
        let text = fs::read_to_string(&path).expect("Swift source is readable");
        for name in ["shared/config", "public.json"] {
            assert!(!text.contains(name), "K-3: {} names {name}", path.display());
        }
    }
}

/// Runs the command line with `args` and returns code, stdout, and stderr.
fn run(args: &[&str]) -> (Option<i32>, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_desktop-codegen"))
        .args(args)
        .output()
        .expect("the binary runs");
    (
        out.status.code(),
        String::from_utf8(out.stdout).expect("stdout is UTF-8"),
        String::from_utf8(out.stderr).expect("stderr is UTF-8"),
    )
}

/// Covers AC-4: `config check` on the repo exits with 0 and prints exactly
/// the success line of `check`; a missing or unknown action exits with 2.
#[test]
fn config_command_exit_codes() {
    let (code, stdout, stderr) = run(&["config", "check"]);
    let line = check(&repo_root(), &config::SOURCE).expect("committed outputs are up to date");
    assert_eq!(code, Some(0), "AC-4: exit code, stderr: {stderr}");
    assert_eq!(stdout, format!("{line}\n"), "AC-4: one success line");
    assert_eq!(stderr, "", "AC-4: nothing on stderr");
    for args in [&["config"][..], &["config", "nope"]] {
        let (code, stdout, stderr) = run(args);
        assert_eq!(code, Some(2), "AC-4: {args:?}");
        assert_eq!(stdout, "", "AC-4: {args:?}");
        assert!(
            stderr
                .lines()
                .nth(1)
                .is_some_and(|line| line.contains("config")),
            "AC-4: the sources line lists config: {stderr}"
        );
    }
}
