/// Covers AC-4: in a fresh root, `check` reports the missing schema without
/// writing, `generate` writes it, `check` then passes with the success
/// line, and a second `generate` writes nothing.
#[test]
fn generate_and_check_round_trip_in_a_fresh_root() {
    let root = fixture("round_trip", false);
    let problems = check(&root, &config::SOURCE).expect_err("the schema is missing");
    assert!(
        problems.iter().any(|problem| problem.path == SCHEMA_PATH
            && problem.message.starts_with(
                "missing, run: cargo run -p desktop-codegen --locked -- config generate"
            )),
        "AC-4: missing schema: {problems:?}"
    );
    assert!(
        !root.join(SCHEMA_PATH).exists(),
        "AC-4: check wrote nothing"
    );

    let (written, line) = generate(&root, &config::SOURCE).expect("generate succeeds");
    assert!(
        written.iter().any(|path| path == SCHEMA_PATH),
        "AC-4: {written:?}"
    );
    assert!(
        line.starts_with("config: ok, schema version 1, 2 build values, "),
        "AC-4: {line}"
    );
    let line = check(&root, &config::SOURCE).expect("outputs are up to date");
    assert!(
        line.starts_with("config: ok, schema version 1, 2 build values, ")
            && line.ends_with(" outputs up to date"),
        "AC-4: {line}"
    );
    let (written, line) = generate(&root, &config::SOURCE).expect("generate succeeds");
    assert!(
        written.is_empty(),
        "AC-4: second generate wrote {written:?}"
    );
    assert!(line.ends_with(", 0 written"), "AC-4: {line}");
    fs::remove_dir_all(&root).expect("the fixture can be removed");
}

/// Covers AC-4: with a broken source and no schema yet, `check` and
/// `generate` report only source problems and write nothing.
#[test]
fn broken_source_writes_nothing() {
    let root = fixture("broken", false);
    fs::write(root.join("shared/config/local.json"), "{}").expect("write");
    edit(&root, PUBLIC_PATH, PRODUCT_LINE, "\"product_name\": \"\"");
    for problems in [
        check(&root, &config::SOURCE).expect_err("the source is broken"),
        generate(&root, &config::SOURCE).expect_err("the source is broken"),
    ] {
        assert!(
            problems
                .iter()
                .all(|problem| problem.message.starts_with("R-")),
            "AC-4: only rule problems: {problems:?}"
        );
    }
    let mut entries: Vec<String> = fs::read_dir(root.join(CONFIG_DIR))
        .expect("readable")
        .map(|entry| {
            entry
                .expect("entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    entries.sort();
    assert_eq!(
        entries,
        ["README.md", "local.json", "public.json"],
        "AC-4: generate wrote nothing"
    );
    assert!(
        !root.join("apps").exists(),
        "AC-4: no OS output was written"
    );
    fs::remove_dir_all(&root).expect("the fixture can be removed");
}

