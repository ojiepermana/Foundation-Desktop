//! Rule tests for the macOS icon document of the `assets` source, spec
//! `macos/0007`, beyond the six cases in `assets_macos_contract.rs`.
//!
//! They lock `svg_copy` at the edges of its steps, `icon_json` for both
//! variants (canonical, exact `$comment` on line 2, platforms), that only
//! the `app-icon` asset is exported, rule `I-1` for every stale shape and
//! the ignored system files, and the `generate` and `check` round trip
//! including a deleted `AppIcon.icon/`. The rules live in
//! `docs/specs/macos/0007-aset-merek-bersama/index.md`. Inputs are copies
//! under `env!("CARGO_TARGET_TMPDIR")`; `shared/assets/` and `apps/macos/`
//! are never edited. Root independence and "a broken source writes nothing
//! under `apps/`" stay in `assets_rules.rs`.

use std::fs;
use std::path::{Path, PathBuf};

use desktop_codegen::assets::macos::{
    ICON_ASSETS_DIR, ICON_DIR, ICON_JSON_COMMENT, ICON_JSON_PATH, icon_json, outputs, svg_copy,
    svg_marker,
};
use desktop_codegen::assets::{self, Asset, MANIFEST_PATH, README_PATH, SCHEMA_PATH, Variants};
use desktop_codegen::json::to_canonical_json;
use desktop_codegen::{Problem, check, generate, repo_root};
use serde_json::Value;

/// The committed `app-icon` source, from the repo root.
const ICON_SOURCE: &str = "shared/assets/source/app-icon.svg";

/// The copy of the `app-icon` source in the icon document.
const ICON_COPY: &str = "apps/macos/Resources/AppIcon.icon/Assets/app-icon.svg";

/// Reads a committed file as text.
fn read(path: &str) -> String {
    fs::read_to_string(repo_root().join(path)).expect("the committed file is readable")
}

/// The marker of the `app-icon` source.
fn marker() -> String {
    svg_marker(ICON_SOURCE)
}

/// Covers AC-1 and AC-3 (`svg_copy` step 2): the declaration is kept on
/// line 1 when `<?xml` is followed by a space, tab, or newline; one newline
/// after `?>` is dropped and other white space is kept.
#[test]
fn svg_copy_keeps_the_declaration_first() {
    let m = marker();
    let cases = [
        (
            "<?xml\tversion=\"1.0\"?>\n<svg/>",
            format!("<?xml\tversion=\"1.0\"?>\n{m}\n<svg/>\n"),
        ),
        (
            "<?xml\nversion=\"1.0\"?><svg/>",
            format!("<?xml\nversion=\"1.0\"?>\n{m}\n<svg/>\n"),
        ),
        (
            "<?xml version=\"1.0\"?>\n\n<svg/>",
            format!("<?xml version=\"1.0\"?>\n{m}\n\n<svg/>\n"),
        ),
        (
            "<?xml version=\"1.0\"?> \n<svg/>",
            format!("<?xml version=\"1.0\"?>\n{m}\n \n<svg/>\n"),
        ),
    ];
    for (input, expected) in cases {
        assert_eq!(svg_copy(ICON_SOURCE, input), expected, "AC-3: {input:?}");
    }
}

/// Covers AC-1 and AC-3 (`svg_copy` step 3): without a declaration that
/// fits step 2 the marker comes first, the body is kept apart from its
/// trailing newlines, and a source's own comment, even one holding `--`,
/// is carried as is (the spec leaves it to `actool`).
#[test]
fn svg_copy_puts_the_marker_first_otherwise() {
    let m = marker();
    let cases = [
        ("<?xml?><svg/>", format!("{m}\n<?xml?><svg/>\n")),
        (
            "<?xmlversion?><svg/>",
            format!("{m}\n<?xmlversion?><svg/>\n"),
        ),
        (
            "<svg>\n\n  <g/>\n</svg>\n\n",
            format!("{m}\n<svg>\n\n  <g/>\n</svg>\n"),
        ),
        (
            "<svg><!-- a -- b --></svg>",
            format!("{m}\n<svg><!-- a -- b --></svg>\n"),
        ),
    ];
    for (input, expected) in cases {
        assert_eq!(svg_copy(ICON_SOURCE, input), expected, "AC-3: {input:?}");
    }
}

/// Covers AC-9: the marker names the source path it was copied from.
#[test]
fn svg_marker_names_its_source() {
    for path in [
        "shared/assets/source/app-icon.svg",
        "shared/assets/source/logo-light.svg",
    ] {
        let marker = svg_marker(path);
        assert!(
            marker.starts_with("<!-- Generated by desktop-codegen from ")
                && marker.contains(&format!(" from {path}. Do not edit."))
                && marker.ends_with(" -->"),
            "AC-9: {marker}"
        );
    }
}

/// Covers AC-3 and AC-9 (`icon_json`): canonical JSON, the exact
/// `$comment` on line 2, macOS squares as the only platform, one group with
/// one layer named after the asset, and the same bytes on every call.
#[test]
fn icon_json_shape_for_both_variants() {
    for (id, variants) in [
        ("app-icon", Variants::Any),
        ("logo-2x", Variants::Any),
        ("app-icon", Variants::LightDark),
    ] {
        let asset = Asset {
            id: id.to_string(),
            variants,
            placeholder: true,
        };
        let text = icon_json(&asset);
        assert_eq!(text, icon_json(&asset), "AC-3: deterministic");
        let value: Value = serde_json::from_str(&text).expect("icon.json is JSON");
        assert_eq!(to_canonical_json(&value), text, "AC-3: canonical");
        assert!(
            text.lines()
                .nth(1)
                .is_some_and(|line| line.contains(ICON_JSON_COMMENT)),
            "AC-9: $comment on line 2"
        );
        assert_eq!(
            value["$comment"].as_str(),
            Some(ICON_JSON_COMMENT),
            "AC-3: $comment"
        );
        assert_eq!(
            value["supported-platforms"],
            serde_json::json!({ "squares": ["macOS"] }),
            "AC-3: platforms"
        );
        let layers = &value["groups"][0]["layers"];
        assert_eq!(
            value["groups"].as_array().map(Vec::len),
            Some(1),
            "AC-3: one group"
        );
        assert_eq!(layers.as_array().map(Vec::len), Some(1), "AC-3: one layer");
        let layer = &layers[0];
        assert_eq!(layer["name"].as_str(), Some(id), "AC-3: layer name");
        match variants {
            Variants::Any => {
                assert_eq!(
                    layer["image-name"].as_str(),
                    Some(format!("{id}.svg").as_str())
                );
                assert!(
                    layer.get("image-name-specializations").is_none(),
                    "AC-3: any"
                );
            }
            Variants::LightDark => {
                assert_eq!(
                    layer["image-name"].as_str(),
                    Some(format!("{id}-light.svg").as_str())
                );
                assert_eq!(
                    layer["image-name-specializations"],
                    serde_json::json!([{ "appearance": "dark", "value": format!("{id}-dark.svg") }]),
                    "AC-3: dark specialization"
                );
            }
        }
    }
}

/// A fresh `assets_macos_rules_<test>` root holding the four committed
/// files of `shared/assets/`, and the icon document when asked.
fn fixture(test: &str, with_icon: bool) -> PathBuf {
    let root = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("assets_macos_rules_{test}"));
    if root.exists() {
        fs::remove_dir_all(&root).expect("the old fixture can be removed");
    }
    fs::create_dir_all(root.join("shared/assets/source")).expect("the folder can be made");
    for path in [README_PATH, MANIFEST_PATH, SCHEMA_PATH, ICON_SOURCE] {
        fs::copy(repo_root().join(path), root.join(path)).expect("the committed file is copied");
    }
    if with_icon {
        generate(&root, &assets::SOURCE).expect("generate succeeds on the copy");
    }
    root
}

/// `(path, rule ID)` of each problem, sorted.
fn ids(problems: &[Problem]) -> Vec<(String, String)> {
    let mut found: Vec<(String, String)> = problems
        .iter()
        .map(|problem| {
            let id = problem.message.split(':').next().unwrap_or_default();
            (problem.path.clone(), id.to_string())
        })
        .collect();
    found.sort();
    found
}

/// Covers AC-1 (E-1): only the `app-icon` asset is exported, even when the
/// manifest lists other assets.
#[test]
fn only_the_app_icon_is_exported() {
    let root = fixture("two_assets", false);
    let manifest = read(MANIFEST_PATH).replacen(
        "\"assets\": {",
        "\"assets\": {\n    \"logo\": {\n      \"variants\": \"light-dark\"\n    },",
        1,
    );
    fs::write(root.join(MANIFEST_PATH), manifest).expect("writable");
    let logo = read(ICON_SOURCE).replace("0 0 1024 1024", "0 0 300 80");
    fs::write(root.join("shared/assets/source/logo-light.svg"), &logo).expect("writable");
    fs::write(root.join("shared/assets/source/logo-dark.svg"), &logo).expect("writable");
    let plan = (assets::SOURCE.plan)(&root).expect("two assets are valid");
    let icon_paths: Vec<&str> = plan
        .outputs
        .iter()
        .map(|output| output.path.as_str())
        .filter(|path| path.starts_with("apps/"))
        .collect();
    assert_eq!(
        icon_paths,
        [ICON_COPY, ICON_JSON_PATH],
        "AC-1: only app-icon"
    );
    fs::remove_dir_all(&root).expect("the fixture can be removed");
}

/// One stale shape: the entry path under `AppIcon.icon`, and how to make it.
type StaleShape = (&'static str, fn(&Path));

/// Covers AC-3 (`I-1`): every stale shape gives one problem on the path of
/// the entry, a subfolder is reported as the folder, and several stale
/// entries are each reported once.
#[test]
fn stale_icon_entries_are_each_reported() {
    let shapes: [StaleShape; 6] = [
        ("Assets/old.svg", |dir| {
            fs::write(dir.join("Assets/old.svg"), "x").expect("write")
        }),
        ("Assets/.hidden", |dir| {
            fs::write(dir.join("Assets/.hidden"), "x").expect("write")
        }),
        ("Assets/empty", |dir| {
            fs::create_dir(dir.join("Assets/empty")).expect("mkdir")
        }),
        ("Assets/sub", |dir| {
            fs::create_dir(dir.join("Assets/sub")).expect("mkdir");
            fs::write(dir.join("Assets/sub/x.svg"), "x").expect("write");
        }),
        ("notes.txt", |dir| {
            fs::write(dir.join("notes.txt"), "x").expect("write")
        }),
        ("extra", |dir| {
            fs::create_dir(dir.join("extra")).expect("mkdir")
        }),
    ];
    for (entry, make) in shapes {
        let root = fixture(&format!("stale_{}", entry.replace(['/', '.'], "_")), true);
        make(&root.join(ICON_DIR));
        let problems = (assets::SOURCE.plan)(&root).expect_err("a stale entry fails plan");
        let path = format!("{ICON_DIR}/{entry}");
        assert_eq!(
            ids(&problems),
            [(path.clone(), "I-1".to_string())],
            "AC-3: {entry}"
        );
        assert_eq!(
            problems[0].message, "I-1: not produced by the generator, remove it",
            "AC-3: {entry}"
        );
        fs::remove_dir_all(&root).expect("the fixture can be removed");
    }

    let root = fixture("stale_many", true);
    fs::write(root.join(ICON_DIR).join("Assets/a.svg"), "x").expect("write");
    fs::write(root.join(ICON_DIR).join("b.txt"), "x").expect("write");
    let problems = (assets::SOURCE.plan)(&root).expect_err("stale entries fail plan");
    assert_eq!(
        ids(&problems),
        [
            (format!("{ICON_ASSETS_DIR}/a.svg"), "I-1".to_string()),
            (format!("{ICON_DIR}/b.txt"), "I-1".to_string()),
        ],
        "AC-3: one problem per stale entry"
    );
    fs::remove_dir_all(&root).expect("the fixture can be removed");
}

/// Covers AC-3 (`I-1`): `icon.json` and `Assets` of the wrong kind are
/// stale, and the system files are ignored in both folders.
#[test]
fn wrong_kinds_are_stale_and_system_files_are_ignored() {
    let root = fixture("wrong_kinds", true);
    let dir = root.join(ICON_DIR);
    fs::remove_file(dir.join("icon.json")).expect("remove");
    fs::create_dir(dir.join("icon.json")).expect("mkdir");
    let problems = (assets::SOURCE.plan)(&root).expect_err("icon.json as a folder");
    assert_eq!(
        ids(&problems),
        [(ICON_JSON_PATH.to_string(), "I-1".to_string())],
        "AC-3"
    );
    fs::remove_dir_all(&root).expect("the fixture can be removed");

    let root = fixture("assets_file", true);
    let dir = root.join(ICON_DIR);
    fs::remove_dir_all(dir.join("Assets")).expect("remove");
    fs::write(dir.join("Assets"), "x").expect("write");
    let problems = (assets::SOURCE.plan)(&root).expect_err("Assets as a file");
    assert_eq!(
        ids(&problems),
        [(ICON_ASSETS_DIR.to_string(), "I-1".to_string())],
        "AC-3"
    );
    fs::remove_dir_all(&root).expect("the fixture can be removed");

    let root = fixture("system_files", true);
    let dir = root.join(ICON_DIR);
    for name in [".DS_Store", "Thumbs.db", "desktop.ini"] {
        fs::write(dir.join(name), "x").expect("write");
        fs::write(dir.join("Assets").join(name), "x").expect("write");
    }
    (assets::SOURCE.plan)(&root).expect("AC-3: system files are ignored");
    check(&root, &assets::SOURCE).expect("AC-3: check passes");
    fs::remove_dir_all(&root).expect("the fixture can be removed");
}

/// Covers AC-3 ("Kasus gagal"): a stale file stops `generate` too, so a
/// missing `icon.json` is not written until the stale file is removed.
#[test]
fn stale_entry_stops_generate() {
    let root = fixture("stale_generate", true);
    let dir = root.join(ICON_DIR);
    fs::write(dir.join("Assets/old.svg"), "x").expect("write");
    fs::remove_file(dir.join("icon.json")).expect("remove");
    generate(&root, &assets::SOURCE).expect_err("a stale file stops generate");
    assert!(!dir.join("icon.json").exists(), "AC-3: nothing written");
    fs::remove_file(dir.join("Assets/old.svg")).expect("remove");
    let (written, _) = generate(&root, &assets::SOURCE).expect("generate succeeds");
    assert_eq!(written, [ICON_JSON_PATH], "AC-3: only the missing file");
    fs::remove_dir_all(&root).expect("the fixture can be removed");
}

/// Covers AC-1 and AC-5: in a fresh root `generate` writes the icon
/// document as planned, `check` passes; after `AppIcon.icon/` is deleted
/// `check` reports both files missing and `generate` writes both again; a
/// hand edit of the copy is reported as that file only.
#[test]
fn generate_and_check_round_trip_for_the_icon_document() {
    let root = fixture("round_trip", true);
    let plan = (assets::SOURCE.plan)(&root).expect("valid");
    let asset = Asset {
        id: "app-icon".to_string(),
        variants: Variants::Any,
        placeholder: true,
    };
    let expected = outputs(&asset, &[read(ICON_SOURCE)]);
    for output in &expected {
        assert!(
            plan.outputs.contains(output),
            "AC-1: {} planned",
            output.path
        );
        let on_disk = fs::read_to_string(root.join(&output.path)).expect("written");
        assert_eq!(on_disk, output.contents, "AC-1: {} as planned", output.path);
    }
    check(&root, &assets::SOURCE).expect("AC-1: check passes");

    fs::remove_dir_all(root.join(ICON_DIR)).expect("remove");
    let problems = check(&root, &assets::SOURCE).expect_err("both files are missing");
    let mut missing: Vec<&str> = problems
        .iter()
        .filter(|p| p.message.starts_with("missing, run: "))
        .map(|p| p.path.as_str())
        .collect();
    missing.sort_unstable();
    assert_eq!(missing, [ICON_COPY, ICON_JSON_PATH], "AC-1: {problems:?}");
    let (written, _) = generate(&root, &assets::SOURCE).expect("generate succeeds");
    assert_eq!(
        written,
        [ICON_COPY, ICON_JSON_PATH],
        "AC-1: both written again"
    );

    fs::write(root.join(ICON_COPY), "<svg").expect("editable");
    let problems = check(&root, &assets::SOURCE).expect_err("a hand edit is caught");
    assert_eq!(problems.len(), 1, "AC-5: {problems:?}");
    assert_eq!(problems[0].path, ICON_COPY);
    assert!(
        problems[0]
            .message
            .starts_with("differs from the generator output"),
        "AC-5: {}",
        problems[0]
    );
    fs::remove_dir_all(&root).expect("the fixture can be removed");
}
