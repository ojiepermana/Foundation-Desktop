//! Contract tests for the macOS output of the `localization` source, spec
//! `macos/0006`.
//!
//! These tests use only the public paths of `desktop_codegen` and the
//! standard library. Each test `mNN_` is one row of the table "Uji emitter"
//! in `docs/specs/macos/0006-satu-contoh-lokalisasi/index.md`. Test catalogs
//! are made by editing the real catalog, with the same edits as K-1 and K-2
//! in `localization_contract.rs` (AC-2).

use std::fs;

use desktop_codegen::localization::{self, macos};
use desktop_codegen::{Output, repo_root};

/// The first line of every `.strings` file.
const MARKER: &str = "/* Generated by desktop-codegen from tooling/codegen/src/localization. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- localization generate */";

/// The expected `en.lproj/Localizable.strings`, as in "Isi berkas".
const EN_STRINGS: &str = "/* Generated by desktop-codegen from tooling/codegen/src/localization. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- localization generate */\n\n/* Label of the button that sends the name and shows the greeting. */\n\"greeting.submit\" = \"Greet\";\n";

/// The expected `id.lproj/Localizable.strings`, as in "Isi berkas".
const ID_STRINGS: &str = "/* Generated by desktop-codegen from tooling/codegen/src/localization. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- localization generate */\n\n/* Label of the button that sends the name and shows the greeting. */\n\"greeting.submit\" = \"Sapa\";\n";

/// Reads the real catalog.
fn real_catalog() -> String {
    fs::read_to_string(repo_root().join(localization::CATALOG_PATH))
        .expect("the catalog is readable")
}

/// Replaces the first `find` with `replace` in `text`.
fn replaced(text: &str, find: &str, replace: &str) -> String {
    assert!(text.contains(find), "{find:?} is not in the catalog");
    text.replacen(find, replace, 1)
}

/// Replaces the first `find` with `replace` in the real catalog.
fn edited(find: &str, replace: &str) -> String {
    replaced(&real_catalog(), find, replace)
}

/// Test catalog K-1: placeholders in a different order per locale.
fn catalog_k1() -> String {
    replaced(
        &edited("\"Greet\"", "\"{name}, welcome to {app}.\""),
        "\"Sapa\"",
        "\"Selamat datang di {app}, {name}.\"",
    )
}

/// Test catalog K-2: a third locale and no `id` text.
fn catalog_k2() -> String {
    replaced(
        &edited("[\"en\", \"id\"]", "[\"en\", \"id\", \"ms\"]"),
        "\"Greet\",\n        \"id\": \"Sapa\"",
        "\"Greet\"",
    )
}

/// The macOS outputs of a catalog text.
fn outputs(catalog: &str) -> Vec<Output> {
    let catalog = localization::parse(catalog)
        .unwrap_or_else(|problems| panic!("the test catalog is valid: {problems:?}"));
    macos::outputs(&catalog)
}

/// The path of the file for `locale`.
fn path(locale: &str) -> String {
    format!(
        "{}/{locale}.lproj/Localizable.strings",
        macos::RESOURCES_DIR
    )
}

/// The contents of the output for `locale`.
fn contents<'a>(outputs: &'a [Output], locale: &str) -> &'a str {
    let wanted = path(locale);
    outputs
        .iter()
        .find(|output| output.path == wanted)
        .map(|output| output.contents.as_str())
        .unwrap_or_else(|| panic!("no output for {locale}"))
}

#[test]
fn m01_real_catalog_writes_one_file_per_locale_after_the_schema() {
    let plan = (localization::SOURCE.plan)(&repo_root()).expect("the catalog is valid");
    let paths: Vec<&str> = plan
        .outputs
        .iter()
        .map(|output| output.path.as_str())
        .collect();
    assert_eq!(
        paths,
        [
            "shared/localization/catalog.schema.json",
            "apps/macos/Presentation/Resources/en.lproj/Localizable.strings",
            "apps/macos/Presentation/Resources/id.lproj/Localizable.strings",
        ]
    );
    assert_eq!(plan.outputs[1].contents, EN_STRINGS);
    assert_eq!(plan.outputs[2].contents, ID_STRINGS);
}

#[test]
fn m02_missing_translations_fall_back_and_are_marked() {
    let outputs = outputs(&catalog_k2());
    let paths: Vec<&str> = outputs.iter().map(|output| output.path.as_str()).collect();
    assert_eq!(paths, [path("en"), path("id"), path("ms")]);
    for locale in ["id", "ms"] {
        let text = contents(&outputs, locale);
        assert!(text.contains("\"greeting.submit\" = \"Greet\";"), "{text}");
        assert!(
            text.contains(&format!(
                "/* Missing translation for {locale}, shows the en text. */"
            )),
            "{text}"
        );
    }
    assert!(!contents(&outputs, "en").contains("Missing translation"));
}

#[test]
fn m03_placeholders_become_positional() {
    let outputs = outputs(&catalog_k1());
    assert!(contents(&outputs, "en").contains("\"greeting.submit\" = \"%1$@, welcome to %2$@.\";"));
    assert!(
        contents(&outputs, "id")
            .contains("\"greeting.submit\" = \"Selamat datang di %2$@, %1$@.\";")
    );
}

#[test]
fn m04_special_characters_are_escaped() {
    let outputs = outputs(&edited(
        "\"Greet\"",
        "\"100% \\\"done\\\" \\\\ *x* _y_ <b> & Łukasz 李\"",
    ));
    let text = contents(&outputs, "en");
    assert!(
        text.contains("\"greeting.submit\" = \"100%% \\\"done\\\" \\\\ *x* _y_ <b> & Łukasz 李\";"),
        "{text}"
    );
}

#[test]
fn m05_repeated_placeholder_keeps_its_number() {
    let catalog = replaced(
        &edited("\"Greet\"", "\"{name} and {name}\""),
        "\"Sapa\"",
        "\"{name} dan {name}\"",
    );
    let outputs = outputs(&catalog);
    assert!(contents(&outputs, "en").contains("\"%1$@ and %1$@\""));
}

#[test]
fn m06_locale_folders_use_catalog_names() {
    let catalog = replaced(
        &edited("[\"en\", \"id\"]", "[\"en\", \"id\", \"pt-BR\"]"),
        "\"id\": \"Sapa\"",
        "\"id\": \"Sapa\", \"pt-BR\": \"Saudar\"",
    );
    let outputs = outputs(&catalog);
    assert_eq!(
        outputs[2].path,
        "apps/macos/Presentation/Resources/pt-BR.lproj/Localizable.strings"
    );
    assert!(
        outputs[2]
            .contents
            .contains("\"greeting.submit\" = \"Saudar\";")
    );
}

#[test]
fn m07_every_file_starts_with_the_marker_and_ends_with_one_newline() {
    for catalog in [real_catalog(), catalog_k1(), catalog_k2()] {
        for output in outputs(&catalog) {
            let text = &output.contents;
            assert_eq!(text.lines().next(), Some(MARKER), "{}", output.path);
            assert!(text.ends_with("\";\n"), "{}", output.path);
            assert!(!text.ends_with("\n\n"), "{}", output.path);
            assert!(!text.contains('\r'), "{}", output.path);
        }
    }
}
