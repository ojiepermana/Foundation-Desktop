//! Writes the JSON schema (draft-07) of `brand.json`.
//!
//! The schema covers the shape only. The ban on ids ending with `-light` or
//! `-dark`, the folder contents, and the content of each source are only
//! checked by `assets check`.

use serde_json::{Value, json};

use super::{ID_PATTERN, REQUIRED_ASSET, SCHEMA_REFERENCE, SCHEMA_VERSION, Variants};
use crate::json::to_canonical_json;

/// The marker at the top of the schema (rule O-1 of spec `_root/0003`).
const MARKER: &str = "Generated by desktop-codegen from tooling/codegen/src/assets. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- assets generate";

/// The schema contents, written with the canonical layout.
pub(super) fn contents() -> String {
    to_canonical_json(&schema())
}

/// The schema of `brand.json`.
fn schema() -> Value {
    let variants: Vec<&str> = Variants::ALL.iter().map(|value| value.as_str()).collect();
    let asset = json!({
        "additionalProperties": false,
        "description": "One brand asset. Its source files are derived from the id: source/<id>.svg for any, source/<id>-light.svg and source/<id>-dark.svg for light-dark.",
        "properties": {
            "placeholder": {
                "description": "True while the source files are temporary markers and not the real brand. Defaults to false.",
                "type": "boolean",
            },
            "variants": {
                "description": "any: one source file for both light and dark appearance. light-dark: one source file per appearance.",
                "enum": variants,
            },
        },
        "required": ["variants"],
        "type": "object",
    });
    let mut patterns = serde_json::Map::new();
    patterns.insert(ID_PATTERN.to_string(), asset);
    json!({
        "$comment": MARKER,
        "$schema": "http://json-schema.org/draft-07/schema#",
        "additionalProperties": false,
        "description": "Manifest of the shared brand assets. An editor aid; the check in desktop-codegen is the authority. Rules: docs/specs/_root/0005-aset-merek-bersama/index.md.",
        "properties": {
            "$schema": {
                "const": SCHEMA_REFERENCE,
                "description": "Relative path to this generated schema.",
            },
            "assets": {
                "additionalProperties": false,
                "description": "One entry per brand asset, keyed by asset id. An id may not end with -light or -dark.",
                "patternProperties": Value::Object(patterns),
                "required": [REQUIRED_ASSET],
                "type": "object",
            },
            "schemaVersion": {
                "const": SCHEMA_VERSION,
                "description": "Version of this manifest shape. Goes up by one on every shape change.",
            },
        },
        "required": ["$schema", "schemaVersion", "assets"],
        "title": format!("Brand asset manifest of the desktop foundation, schema version {SCHEMA_VERSION}"),
        "type": "object",
    })
}
