//! The macOS output of the `assets` source: the Icon Composer document
//! `apps/macos/Resources/AppIcon.icon`, compiled by Xcode's `actool` at
//! build time.
//!
//! Design: `docs/specs/macos/0007-aset-merek-bersama/index.md`. Both files
//! are text, so the tool never writes binary output. The code is host
//! neutral.

use serde_json::{Value, json};

use super::{Asset, Variants};
use crate::Output;
use crate::json::to_canonical_json;

/// The icon document folder, from the repo root.
pub const ICON_DIR: &str = "apps/macos/Resources/AppIcon.icon";

/// The icon document manifest, from the repo root.
pub const ICON_JSON_PATH: &str = "apps/macos/Resources/AppIcon.icon/icon.json";

/// The folder of the SVG layers of the icon document, from the repo root.
pub const ICON_ASSETS_DIR: &str = "apps/macos/Resources/AppIcon.icon/Assets";

/// The `$comment` marker of `icon.json` (rule O-1 of spec `_root/0003`).
pub const ICON_JSON_COMMENT: &str = "Generated by desktop-codegen from tooling/codegen/src/assets/macos.rs. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- assets generate";

/// The XML comment that marks a copied SVG source. It never holds `--`,
/// because XML forbids it inside a comment and `actool` rejects such files.
pub fn svg_marker(source_path: &str) -> String {
    format!(
        "<!-- Generated by desktop-codegen from {source_path}. Do not edit. To regenerate, run the assets generate command of desktop-codegen. -->"
    )
}

/// The copy of an SVG source with the marker in front, after the
/// `<?xml ... ?>` declaration when there is one, ending in one newline.
pub fn svg_copy(source_path: &str, contents: &str) -> String {
    let marker = svg_marker(source_path);
    let body = contents.trim_end_matches('\n');
    let declaration = body
        .strip_prefix("<?xml")
        .filter(|after| after.starts_with([' ', '\t', '\n']))
        .and_then(|_| body.find("?>"));
    match declaration {
        Some(end) => {
            let (decl, rest) = body.split_at(end + 2);
            let rest = rest.strip_prefix('\n').unwrap_or(rest);
            format!("{decl}\n{marker}\n{rest}\n")
        }
        None => format!("{marker}\n{body}\n"),
    }
}

/// The `icon.json` of the icon document for `asset`: one group with one
/// layer, and a dark appearance file for a `light-dark` asset.
pub fn icon_json(asset: &Asset) -> String {
    let id = &asset.id;
    let layer = match asset.variants {
        Variants::Any => json!({
            "image-name": format!("{id}.svg"),
            "name": id,
        }),
        Variants::LightDark => json!({
            "image-name": format!("{id}-light.svg"),
            "image-name-specializations": [
                { "appearance": "dark", "value": format!("{id}-dark.svg") },
            ],
            "name": id,
        }),
    };
    let document: Value = json!({
        "$comment": ICON_JSON_COMMENT,
        "groups": [ { "layers": [layer] } ],
        "supported-platforms": { "squares": ["macOS"] },
    });
    to_canonical_json(&document)
}

/// One SVG copy per source of `asset`, in the order of
/// `Asset::source_paths`, then `icon.json`. `contents` holds the text of
/// each source path, in the same order.
pub fn outputs(asset: &Asset, contents: &[String]) -> Vec<Output> {
    let paths = asset.source_paths();
    assert_eq!(contents.len(), paths.len(), "one content per source path");
    let mut outputs: Vec<Output> = paths
        .iter()
        .zip(contents)
        .map(|(path, text)| {
            let name = path.rsplit('/').next().unwrap_or(path);
            Output {
                path: format!("{ICON_ASSETS_DIR}/{name}"),
                contents: svg_copy(path, text),
            }
        })
        .collect();
    outputs.push(Output {
        path: ICON_JSON_PATH.to_string(),
        contents: icon_json(asset),
    });
    outputs
}
