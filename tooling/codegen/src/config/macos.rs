//! The macOS output of the `config` source: `apps/macos/Config/Shared.xcconfig`.
//!
//! The file carries the three settings Xcode derives from the shared public
//! values (spec `macos/0004`,
//! `docs/specs/macos/0004-konfigurasi-publik/index.md`). The code here is
//! host neutral: no `cfg` attributes and no new dependencies.

use crate::{Output, Problem};

/// The generated settings file, from the repo root.
pub const SHARED_XCCONFIG_PATH: &str = "apps/macos/Config/Shared.xcconfig";

/// The suffix the macOS bundle identifier adds to `build.app_identifier`
/// (the derivation rule `K-6` of spec `_root/0004`).
pub const BUNDLE_IDENTIFIER_SUFFIX: &str = ".macos";

/// The public values file the product name comes from, for `M-1`.
const PUBLIC_PATH: &str = "shared/config/public.json";

/// The manifest the workspace version comes from, for `M-2`.
const VERSION_PATH: &str = "Cargo.toml";

/// The two fixed comment lines at the top of the file (rule O-1 of spec
/// `_root/0003`).
const HEADER: &str = "// Generated by desktop-codegen from shared/config/public.json and the workspace version. Do not edit.\n// Run: cargo run -p desktop-codegen --locked -- config generate\n";

/// Builds `apps/macos/Config/Shared.xcconfig` from the product name, the
/// application identifier base, and the workspace version.
///
/// A pure function: it reads no files and no environment. It reports every
/// rule that fails (`M-1` for the product name, `M-2` for the version).
pub fn shared_xcconfig(
    product_name: &str,
    app_identifier: &str,
    version: &str,
) -> Result<Output, Vec<Problem>> {
    let mut problems = Vec::new();
    if let Some(reason) = product_name_problem(product_name) {
        problems.push(Problem::new(
            PUBLIC_PATH,
            format!(
                "M-1: build.product_name {reason}, so it cannot be carried by an xcconfig file"
            ),
        ));
    }
    if !is_plain_version(version) {
        problems.push(Problem::new(
            VERSION_PATH,
            format!(
                "M-2: version {version} must be exactly three decimal numbers separated by dots"
            ),
        ));
    }
    if !problems.is_empty() {
        return Err(problems);
    }
    let contents = format!(
        "{HEADER}INFOPLIST_KEY_CFBundleDisplayName = {product_name}\nMARKETING_VERSION = {version}\nPRODUCT_BUNDLE_IDENTIFIER = {app_identifier}{BUNDLE_IDENTIFIER_SUFFIX}\n"
    );
    Ok(Output {
        path: SHARED_XCCONFIG_PATH.to_string(),
        contents,
    })
}

/// Why a product name does not survive xcconfig parsing, if it does not
/// (`M-1`): `//` starts a comment, `$` starts a setting reference, a final
/// `;` is dropped, and a final `\` joins the next line.
fn product_name_problem(name: &str) -> Option<&'static str> {
    if name.contains("//") {
        Some("contains //")
    } else if name.contains('$') {
        Some("contains $")
    } else if name.ends_with(';') {
        Some("ends with ;")
    } else if name.ends_with('\\') {
        Some("ends with \\")
    } else {
        None
    }
}

/// Whether `version` is exactly three decimal numbers separated by dots
/// (`M-2`), such as `0.1.0`.
fn is_plain_version(version: &str) -> bool {
    let parts: Vec<&str> = version.split('.').collect();
    parts.len() == 3
        && parts
            .iter()
            .all(|part| !part.is_empty() && part.chars().all(|c| c.is_ascii_digit()))
}
