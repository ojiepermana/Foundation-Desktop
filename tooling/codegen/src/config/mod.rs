//! The `config` source: public values under `shared/config/` that must be
//! the same in the macOS, Windows, and Linux apps.
//!
//! [`SOURCE`] checks the rules R-1 to R-3 of spec `_root/0004`
//! (`docs/specs/_root/0004-konfigurasi-publik/index.md`) and plans the
//! generated `shared/config/public.schema.json`. The schema is built from
//! the same constants the check uses, so the two cannot disagree.

use std::fs;
use std::path::Path;

use serde::Deserialize;
use serde_json::{Value, json};

use crate::json::to_canonical_json;
use crate::{Output, Plan, Problem, Source};

pub mod macos;

/// The `config` source, run as `desktop-codegen config <check|generate>`.
pub const SOURCE: Source = Source {
    name: "config",
    plan,
};

/// The only schema version the check knows.
pub const SCHEMA_VERSION: u64 = 1;

/// The longest `build.app_identifier`, in characters.
pub const MAX_APP_IDENTIFIER: usize = 100;

/// The shared config folder, from the repo root.
pub const CONFIG_DIR: &str = "shared/config";

/// The public values, from the repo root.
pub const PUBLIC_PATH: &str = "shared/config/public.json";

/// The folder guide that records the schema history, from the repo root.
pub const README_PATH: &str = "shared/config/README.md";

/// The generated schema, from the repo root.
pub const SCHEMA_PATH: &str = "shared/config/public.schema.json";

/// The value `$schema` must have in `public.json`.
const SCHEMA_REFERENCE: &str = "./public.schema.json";

/// Folder entries that are ignored by R-1.
const IGNORED_ENTRIES: [&str; 1] = [".DS_Store"];

/// The keys of the `build` group, in the order the schema requires them.
const BUILD_KEYS: [&str; 2] = ["product_name", "app_identifier"];

/// The keys of the top level object, in the order the schema requires them.
const TOP_KEYS: [&str; 3] = ["$schema", "schemaVersion", "build"];

/// The pattern of `build.app_identifier`, matching [`check_app_identifier`].
const APP_IDENTIFIER_PATTERN: &str =
    r"^[A-Za-z]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z]([A-Za-z0-9-]*[A-Za-z0-9])?)+$";

/// The marker at the top of the schema (rule O-1 of spec `_root/0003`).
const MARKER: &str = "Generated by desktop-codegen from tooling/codegen/src/config. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- config generate";

/// `public.json` as written.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct PublicFile {
    #[serde(rename = "$schema")]
    schema: String,
    #[serde(rename = "schemaVersion")]
    schema_version: u64,
    build: Build,
}

/// The `build` group of `public.json`.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Build {
    product_name: String,
    app_identifier: String,
}

/// Checks `shared/config/` under `root` and plans the schema output.
fn plan(root: &Path) -> Result<Plan, Vec<Problem>> {
    let mut problems = Vec::new();
    check_entries(root, &mut problems);

    let public = read_public(root, &mut problems);
    if let Some(file) = &public {
        check_public(file, &mut problems);
        if file.schema_version != SCHEMA_VERSION {
            problems.push(Problem::new(
                PUBLIC_PATH,
                format!(
                    "R-3: schemaVersion is {}, the known schema version is {SCHEMA_VERSION}",
                    file.schema_version
                ),
            ));
        }
    }
    check_readme_version(root, &mut problems);

    if !problems.is_empty() {
        return Err(problems);
    }
    let Some(file) = public else {
        return Err(problems);
    };
    let xcconfig = macos::shared_xcconfig(
        &file.build.product_name,
        &file.build.app_identifier,
        env!("CARGO_PKG_VERSION"),
    )?;
    Ok(Plan {
        outputs: vec![
            Output {
                path: SCHEMA_PATH.to_string(),
                contents: to_canonical_json(&schema()),
            },
            xcconfig,
        ],
        summary: format!(
            "schema version {SCHEMA_VERSION}, {} build values",
            BUILD_KEYS.len()
        ),
    })
}

/// R-1: the folder holds `public.json` and `README.md`, may hold the
/// generated schema, and holds nothing else except ignored entries.
fn check_entries(root: &Path, problems: &mut Vec<Problem>) {
    let required = [PUBLIC_PATH, README_PATH];
    let allowed = [PUBLIC_PATH, README_PATH, SCHEMA_PATH];
    let mut found = Vec::new();
    match fs::read_dir(root.join(CONFIG_DIR)) {
        Ok(entries) => {
            let mut entries: Vec<_> = entries.filter_map(Result::ok).collect();
            entries.sort_by_key(|entry| entry.file_name());
            for entry in entries {
                let name = entry.file_name().to_string_lossy().into_owned();
                if IGNORED_ENTRIES.contains(&name.as_str()) {
                    continue;
                }
                let path = format!("{CONFIG_DIR}/{name}");
                let is_file = entry.file_type().is_ok_and(|kind| kind.is_file());
                if is_file && allowed.contains(&path.as_str()) {
                    found.push(path);
                } else {
                    problems.push(Problem::new(&path, "R-1: unexpected entry"));
                }
            }
        }
        Err(error) => problems.push(Problem::new(
            CONFIG_DIR,
            format!("R-1: cannot read the folder: {error}"),
        )),
    }
    for path in required {
        if !found.iter().any(|seen| seen == path) {
            problems.push(Problem::new(path, "R-1: missing required file"));
        }
    }
}

/// Reads `public.json` into its closed type, or records an R-2 problem.
/// A missing file is already reported by R-1, so it gives no problem here.
fn read_public(root: &Path, problems: &mut Vec<Problem>) -> Option<PublicFile> {
    let bytes = fs::read(root.join(PUBLIC_PATH)).ok()?;
    let Ok(text) = String::from_utf8(bytes) else {
        problems.push(Problem::new(PUBLIC_PATH, "R-2: not valid UTF-8 text"));
        return None;
    };
    match serde_json::from_str(&text) {
        Ok(file) => Some(file),
        Err(error) => {
            problems.push(Problem::new(PUBLIC_PATH, format!("R-2: {error}")));
            None
        }
    }
}

/// R-2: the rules on values that the closed type alone does not enforce.
fn check_public(file: &PublicFile, problems: &mut Vec<Problem>) {
    let mut push = |message: String| problems.push(Problem::new(PUBLIC_PATH, message));
    if file.schema != SCHEMA_REFERENCE {
        push(format!(
            "R-2: $schema: expected {SCHEMA_REFERENCE}, found {}",
            file.schema
        ));
    }
    if let Some(reason) = check_product_name(&file.build.product_name) {
        push(format!("R-2: build.product_name: {reason}"));
    }
    if let Some(reason) = check_app_identifier(&file.build.app_identifier) {
        push(format!("R-2: build.app_identifier: {reason}"));
    }
}

/// Why `name` is not a valid product name, if it is not.
fn check_product_name(name: &str) -> Option<&'static str> {
    let (Some(first), Some(last)) = (name.chars().next(), name.chars().next_back()) else {
        return Some("must have at least one character");
    };
    if name
        .chars()
        .any(|c| c.is_control() || c == '\u{2028}' || c == '\u{2029}')
    {
        return Some("must not contain control characters or line separators");
    }
    let edge = |c: char| c.is_whitespace() || c == '\u{feff}';
    if edge(first) || edge(last) {
        return Some("must not start or end with whitespace");
    }
    None
}

/// Why `identifier` is not a valid application identifier base, if it is
/// not. Matches [`APP_IDENTIFIER_PATTERN`] and [`MAX_APP_IDENTIFIER`].
fn check_app_identifier(identifier: &str) -> Option<String> {
    if identifier.chars().count() > MAX_APP_IDENTIFIER {
        return Some(format!("must have at most {MAX_APP_IDENTIFIER} characters"));
    }
    let segments: Vec<&str> = identifier.split('.').collect();
    if segments.len() < 2 {
        return Some("needs two or more segments separated by one dot".to_string());
    }
    for segment in segments {
        let valid = segment
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_alphabetic())
            && segment
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-')
            && !segment.ends_with('-');
        if !valid {
            return Some(format!(
                "segment {segment:?} must start with an ASCII letter, hold only ASCII letters, digits, and '-', and not end with '-'"
            ));
        }
    }
    None
}

/// R-3: the version in the last schema history row of `README.md` is the
/// known schema version. A missing `README.md` is already reported by R-1.
fn check_readme_version(root: &Path, problems: &mut Vec<Problem>) {
    let Ok(text) = fs::read_to_string(root.join(README_PATH)) else {
        return;
    };
    let version = text
        .lines()
        .map(|line| line.trim_end_matches('\r'))
        .rfind(|line| {
            line.strip_prefix("| ")
                .is_some_and(|rest| rest.starts_with(|c: char| c.is_ascii_digit()))
        })
        .and_then(|line| line.split('|').nth(1))
        .map(str::trim);
    match version {
        None => problems.push(Problem::new(
            README_PATH,
            "R-3: no schema history row starting with a version number",
        )),
        Some(version) if version.parse::<u64>() == Ok(SCHEMA_VERSION) => {}
        Some(version) => problems.push(Problem::new(
            README_PATH,
            format!(
                "R-3: the last schema history row has version {version}, the known schema version is {SCHEMA_VERSION}"
            ),
        )),
    }
}

/// The JSON schema (draft-07) of `public.json`, an aid for editors.
fn schema() -> Value {
    json!({
        "$comment": MARKER,
        "$schema": "http://json-schema.org/draft-07/schema#",
        "additionalProperties": false,
        "description": "Public values that must be the same in the macOS, Windows, and Linux apps. An editor aid; the check in desktop-codegen is the authority. Rules: docs/specs/_root/0004-konfigurasi-publik/index.md.",
        "properties": {
            "$schema": {
                "const": SCHEMA_REFERENCE,
                "description": "Relative path to this generated schema.",
            },
            "build": {
                "additionalProperties": false,
                "description": "Values each app takes in at build time.",
                "properties": {
                    "app_identifier": {
                        "description": "Reverse DNS base of the application identifier. Each OS derives its own identifier from it.",
                        "maxLength": MAX_APP_IDENTIFIER,
                        "pattern": APP_IDENTIFIER_PATTERN,
                        "type": "string",
                    },
                    "product_name": {
                        "description": "Product name shown to people, the same in every language. No control characters, no line separators, no whitespace at either end.",
                        "minLength": 1,
                        "type": "string",
                    },
                },
                "required": BUILD_KEYS,
                "type": "object",
            },
            "schemaVersion": {
                "const": SCHEMA_VERSION,
                "description": "Version of this schema. Goes up by one on every schema change.",
            },
        },
        "required": TOP_KEYS,
        "title": format!("Public configuration of the desktop foundation, schema version {SCHEMA_VERSION}"),
        "type": "object",
    })
}
