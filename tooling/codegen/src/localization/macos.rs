//! The macOS output of the `localization` source: one `Localizable.strings`
//! file per catalog language, a resource of the Swift module `Presentation`.
//!
//! Design: `docs/specs/macos/0006-satu-contoh-lokalisasi/index.md`. The text
//! of every entry is written as plain text: `\`, `"`, and `%` are escaped,
//! and `{name}` placeholders become positional `%<n>$@` arguments in the
//! order of `Entry::placeholders`. The code is host neutral.

use super::{Catalog, Entry, Origin};
use crate::Output;

/// The folder that holds one `<locale>.lproj` folder per catalog language,
/// from the repo root.
pub const RESOURCES_DIR: &str = "apps/macos/Presentation/Resources";

/// The first line of every file (rule O-1 of spec `_root/0003`). The same
/// text as the marker of the catalog schema.
const MARKER: &str = "/* Generated by desktop-codegen from tooling/codegen/src/localization. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- localization generate */";

/// One `Localizable.strings` output per entry of `Catalog::locales`, in
/// that order. Never fails, because the catalog is already valid.
pub fn outputs(catalog: &Catalog) -> Vec<Output> {
    catalog
        .locales
        .iter()
        .map(|locale| Output {
            path: format!("{RESOURCES_DIR}/{locale}.lproj/Localizable.strings"),
            contents: file(catalog, locale),
        })
        .collect()
}

/// The contents of the file for `locale`.
fn file(catalog: &Catalog, locale: &str) -> String {
    let mut out = String::from(MARKER);
    out.push('\n');
    for entry in &catalog.entries {
        let Some(text) = entry.texts.iter().find(|text| text.locale == locale) else {
            continue;
        };
        out.push('\n');
        out.push_str(&format!("/* {} */\n", entry.description));
        if text.origin == Origin::Fallback {
            out.push_str(&format!(
                "/* Missing translation for {locale}, shows the {} text. */\n",
                catalog.source_locale
            ));
        }
        out.push_str(&format!(
            "\"{}\" = \"{}\";\n",
            entry.key,
            escaped(entry, &text.value)
        ));
    }
    out
}

/// The text with `\`, `"`, and `%` escaped and each `{name}` placeholder
/// turned into `%<n>$@`, with `<n>` its 1 based position in
/// `Entry::placeholders`.
fn escaped(entry: &Entry, value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    let mut chars = value.chars();
    while let Some(c) = chars.next() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '%' => out.push_str("%%"),
            '{' => {
                let name: String = chars.by_ref().take_while(|c| *c != '}').collect();
                let position = entry
                    .placeholders
                    .iter()
                    .position(|placeholder| *placeholder == name)
                    .map_or(0, |index| index + 1);
                out.push_str(&format!("%{position}$@"));
            }
            other => out.push(other),
        }
    }
    out
}
