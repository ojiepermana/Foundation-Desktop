//! Writes the JSON schema (draft-07) of the localization catalog.
//!
//! The schema covers the shape only. The text and placeholder rules (L-6,
//! L-7) and the rules across values (L-5) are only checked by
//! `localization check`.

use serde_json::{Value, json};

use super::{DESCRIPTION_PATTERN, KEY_PATTERN, LOCALE_PATTERN, SCHEMA_REFERENCE, SCHEMA_VERSION};
use crate::json::to_canonical_json;

/// The marker at the top of the schema (rule O-1 of spec `_root/0003`).
const MARKER: &str = "Generated by desktop-codegen from tooling/codegen/src/localization. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- localization generate";

/// The schema contents, written with the canonical layout.
pub(super) fn contents() -> String {
    to_canonical_json(&schema())
}

/// The schema of `catalog.json`.
fn schema() -> Value {
    let locale = json!({ "pattern": LOCALE_PATTERN, "type": "string" });
    json!({
        "$comment": MARKER,
        "$schema": "http://json-schema.org/draft-07/schema#",
        "additionalProperties": false,
        "properties": {
            "$schema": { "const": SCHEMA_REFERENCE },
            "entries": {
                "additionalProperties": {
                    "additionalProperties": false,
                    "properties": {
                        "description": { "pattern": DESCRIPTION_PATTERN, "type": "string" },
                        "text": {
                            "additionalProperties": { "minLength": 1, "type": "string" },
                            "propertyNames": { "pattern": LOCALE_PATTERN },
                            "type": "object",
                        },
                    },
                    "required": ["description", "text"],
                    "type": "object",
                },
                "propertyNames": { "pattern": KEY_PATTERN },
                "type": "object",
            },
            "locales": {
                "items": locale,
                "minItems": 1,
                "type": "array",
                "uniqueItems": true,
            },
            "schemaVersion": { "const": SCHEMA_VERSION },
            "sourceLocale": locale,
        },
        "required": ["$schema", "schemaVersion", "sourceLocale", "locales", "entries"],
        "title": "Localization catalog",
        "type": "object",
    })
}
