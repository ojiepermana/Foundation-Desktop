//! Writes the JSON schemas (draft-07) of the three token files.
//!
//! The schemas are built from the same constants the validator uses, so
//! they cover the shape rules (T-1 to T-5 and T-9). The rules across values
//! (T-6, T-7, T-8, and name collisions in T-3) are only checked by
//! `tokens check`.

use serde_json::{Value, json};

use super::{
    COLOR_PATTERN, DESCRIPTION_PATTERN, MAX_SPACE, NAME_PATTERN, RoleName, SCHEMA_VERSION, Weight,
};
use crate::Output;
use crate::json::to_canonical_json;

/// The marker at the top of every schema (rule O-1).
const MARKER: &str = "Generated by desktop-codegen from tooling/codegen/src/tokens. Do not edit. To regenerate, run: cargo run -p desktop-codegen --locked -- tokens generate";

/// The JSON Schema draft every schema declares.
const DRAFT: &str = "http://json-schema.org/draft-07/schema#";

/// The three schemas, in the order colors, spacing, typography.
pub(super) fn outputs() -> Vec<Output> {
    vec![
        output("colors.schema.json", colors()),
        output("spacing.schema.json", spacing()),
        output("typography.schema.json", typography()),
    ]
}

/// Wraps one schema as an output under `design-system/schemas/`.
fn output(file: &str, schema: Value) -> Output {
    Output {
        path: format!("design-system/schemas/{file}"),
        contents: to_canonical_json(&schema),
    }
}

/// The parts every token file shares: marker, draft, header, and title.
fn document(file: &str, title: &str, mut properties: Value, required: &[&str]) -> Value {
    if let Some(map) = properties.as_object_mut() {
        map.insert(
            "$schema".to_string(),
            json!({ "const": format!("../schemas/{file}") }),
        );
        map.insert(
            "schemaVersion".to_string(),
            json!({ "const": SCHEMA_VERSION }),
        );
    }
    json!({
        "$comment": MARKER,
        "$schema": DRAFT,
        "additionalProperties": false,
        "properties": properties,
        "required": required,
        "title": title,
        "type": "object",
    })
}

/// A string that must match `pattern`.
fn text(pattern: &str) -> Value {
    json!({ "pattern": pattern, "type": "string" })
}

/// A closed object with the given properties and required keys.
fn closed(properties: Value, required: &[&str]) -> Value {
    json!({
        "additionalProperties": false,
        "properties": properties,
        "required": required,
        "type": "object",
    })
}

/// A group of named tokens, each shaped like `entry`.
fn group(entry: Value, non_empty: bool) -> Value {
    let mut value = json!({
        "additionalProperties": entry,
        "propertyNames": { "pattern": NAME_PATTERN },
        "type": "object",
    });
    if non_empty && let Some(map) = value.as_object_mut() {
        map.insert("minProperties".to_string(), json!(1));
    }
    value
}

/// Schema of `colors.json`.
fn colors() -> Value {
    let base = closed(
        json!({
            "placeholder": { "type": "boolean" },
            "value": text(COLOR_PATTERN),
        }),
        &["value"],
    );
    let semantic = closed(
        json!({
            "dark": text(NAME_PATTERN),
            "description": text(DESCRIPTION_PATTERN),
            "light": text(NAME_PATTERN),
            "on": text(NAME_PATTERN),
        }),
        &["description", "light", "dark"],
    );
    document(
        "colors.schema.json",
        "Color tokens",
        json!({ "base": group(base, false), "semantic": group(semantic, true) }),
        &["$schema", "schemaVersion", "base", "semantic"],
    )
}

/// Schema of `spacing.json`.
fn spacing() -> Value {
    let base = closed(
        json!({
            "value": { "maximum": MAX_SPACE, "minimum": 0, "type": "integer" },
        }),
        &["value"],
    );
    let semantic = closed(
        json!({
            "description": text(DESCRIPTION_PATTERN),
            "ref": text(NAME_PATTERN),
        }),
        &["description", "ref"],
    );
    document(
        "spacing.schema.json",
        "Spacing tokens",
        json!({ "base": group(base, false), "semantic": group(semantic, true) }),
        &["$schema", "schemaVersion", "base", "semantic"],
    )
}

/// Schema of `typography.json`.
fn typography() -> Value {
    let weights: Vec<&str> = Weight::ALL.iter().map(|weight| weight.as_str()).collect();
    let roles: Vec<&str> = RoleName::ALL.iter().map(|role| role.as_str()).collect();
    let role = closed(
        json!({
            "description": text(DESCRIPTION_PATTERN),
            "weight": { "enum": weights },
        }),
        &["description", "weight"],
    );
    document(
        "typography.schema.json",
        "Typography tokens",
        json!({
            "roles": {
                "additionalProperties": role,
                "minProperties": 1,
                "propertyNames": { "enum": roles },
                "type": "object",
            },
        }),
        &["$schema", "schemaVersion", "roles"],
    )
}
